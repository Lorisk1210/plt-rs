"""Generate src/layout/ot_tags/tables.rs: HarfBuzz's tables turning BCP 47
language tags into OpenType language system tags.

The data comes from HarfBuzz 14.1.0, the version matplotlib 3.11 is built
with: ``src/hb-ot-tag-table.hh`` (itself generated by HarfBuzz's
``gen-tag-table.py`` from the IANA Language Subtag Registry and Microsoft's
list of OpenType language system tags), and the copyright notice of
``src/hb-ot-tag.cc``.  Pass the directory holding both files:

    mkdir hbsrc && cd hbsrc
    for f in hb-ot-tag-table.hh hb-ot-tag.cc; do
        curl -sSLO https://raw.githubusercontent.com/harfbuzz/harfbuzz/14.1.0/src/$f
    done
    cd .. && python3 -I crates/plt-font/tools/gen_ot_language_tags.py hbsrc

The tables are ``ot_languages2``, ``ot_languages3``,
``ot_languages3_multi`` (with ``ot_languages3_multi_values`` folded in) and
``ot_languages3_blocked``.  ``hb_ot_tags_from_complex_language`` becomes a
list of rules, in HarfBuzz's order, each a pattern (one of the four kinds
of test the C function makes) and the tags it yields; every construct of the
C function is recognised explicitly and anything else stops the generator.
"""

import pathlib
import re
import sys

OUT = (pathlib.Path(__file__).resolve().parent.parent
       / "src" / "layout" / "ot_tags" / "tables.rs")

HB_TAG = r"HB_TAG\s*\('(.)','(.)','(.)','(.)'\)"


def tag(chars):
    """The four characters of a parsed ``HB_TAG``."""
    return "".join(chars)


def rust_tag(text):
    return f'Tag::new(b"{text}")'


def rust_bytes(text):
    assert all(32 < ord(c) < 127 and c not in '"\\' for c in text), text
    return f'b"{text}"'


def comment(text):
    """A C comment's text cleaned for a Rust line comment."""
    return " ".join(text.replace("*/", "").split())


def array_body(source, name):
    """The initializer text of ``static const ... name[] = { ... };``."""
    match = re.search(r"static const \w+ " + name + r"\[\] = \{\n(.*?)\n\};", source, re.S)
    assert match, f"no table {name}"
    return match.group(1)


def parse_lang_tags(source, name, width):
    """``{HB_TAG(language), HB_TAG(tag)}, /* comment */`` entries."""
    entries = []
    for line in array_body(source, name).splitlines():
        match = re.fullmatch(r"\s*\{" + HB_TAG + r",\s*" + HB_TAG + r"\},\s*/\* (.*) \*/", line)
        assert match, f"{name}: unrecognised line {line!r}"
        language = tag(match.group(1, 2, 3, 4))
        assert language[width:] == " " * (4 - width), language
        entries.append((language[:width], tag(match.group(5, 6, 7, 8)), comment(match.group(9))))
    keys = [language for language, _, _ in entries]
    assert keys == sorted(keys), f"{name} is not sorted"
    return entries


def parse_blocked(source):
    blocked = []
    for line in array_body(source, "ot_languages3_blocked").splitlines():
        match = re.fullmatch(r"\s*" + HB_TAG + r",\s*/\* (.*) \*/", line)
        assert match, f"ot_languages3_blocked: unrecognised line {line!r}"
        language = tag(match.group(1, 2, 3, 4))
        assert language[3] == " ", language
        blocked.append((language[:3], comment(match.group(5))))
    assert blocked == sorted(blocked), "ot_languages3_blocked is not sorted"
    return blocked


def parse_multi(source):
    """``ot_languages3_multi`` with the tags of each language resolved."""
    values = [tag(m) for m in re.findall(HB_TAG, array_body(source, "ot_languages3_multi_values"))]
    entries = []
    for line in array_body(source, "ot_languages3_multi").splitlines():
        match = re.fullmatch(r"\s*\{" + HB_TAG + r",\s*(\d+),\s*(\d+)\},\s*/\* (.*) \*/", line)
        assert match, f"ot_languages3_multi: unrecognised line {line!r}"
        language = tag(match.group(1, 2, 3, 4))
        offset, count = int(match.group(5)), int(match.group(6))
        assert language[3] == " " and offset + count <= len(values), line
        entries.append((language[:3], values[offset:offset + count], comment(match.group(7))))
    assert [e[0] for e in entries] == sorted(e[0] for e in entries), "multi is not sorted"
    return entries


def complex_function(source):
    """The body of ``hb_ot_tags_from_complex_language``."""
    start = source.index("hb_ot_tags_from_complex_language (const char")
    body_start = source.index("\n{\n", start) + 3
    body_end = source.index("\n}\n", body_start)
    return source[body_start:body_end]


def statements(text):
    """``(condition, body)`` of every ``if (...) { ... }`` in `text`, which
    must hold nothing else but whitespace, comments, ``case`` labels and
    ``break``."""
    position = 0
    while True:
        match = re.compile(r"\s*(?:break;\s*)?(?:case '(.)':\s*)?if \(").match(text, position)
        if not match:
            assert re.fullmatch(r"\s*(?:break;\s*)?", text[position:]), text[position:position + 80]
            return
        depth, i = 1, match.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        condition = text[match.end():i - 1]
        brace = re.compile(r"\s*\{").match(text, i)
        assert brace, f"no block after if ({condition})"
        depth, j = 1, brace.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        yield match.group(1), " ".join(condition.split()), text[brace.end():j - 1]
        position = j


def pattern(condition, case):
    """The Rust pattern of one condition of the matcher (`case` is the first
    letter the enclosing ``switch`` matched, ``None`` before the switch)."""
    if case is None:
        match = re.fullmatch(r'subtag_matches \(p, limit, "([^"]+)", (\d+)\)', condition)
        assert match and len(match.group(1)) == int(match.group(2)), condition
        return f"Variant({rust_bytes(match.group(1))})"
    match = re.fullmatch(r'lang_matches \(&lang_str\[1\], limit, "([^"]+)", (\d+)\)', condition)
    if match:
        assert len(match.group(1)) == int(match.group(2)), condition
        return f"Prefix({rust_bytes(case + match.group(1))})"
    match = re.fullmatch(r'0 == strcmp \(&lang_str\[1\], "([^"]+)"\)', condition)
    if match:
        return f"Exact({rust_bytes(case + match.group(1))})"
    match = re.fullmatch(r'0 == strncmp \(&lang_str\[1\], "([^"]+)", (\d+)\) '
                         r'&& subtag_matches \(lang_str, limit, "([^"]+)", (\d+)\)', condition)
    assert match, f"unrecognised condition {condition!r}"
    prefix, subtag = match.group(1), match.group(3)
    assert len(prefix) == int(match.group(2)) and len(subtag) == int(match.group(4)), condition
    return f"PrefixWithSubtag({rust_bytes(case + prefix)}, {rust_bytes(subtag)})"


def outcome(body):
    """The description and tags of one rule's block."""
    description = comment(re.match(r"\s*/\* (.*?) \*/", body).group(1))
    single = re.fullmatch(r"\s*/\*[^*]*\*/\s*tags\[0\] = " + HB_TAG
                          + r";\s*/\*[^*]*\*/\s*\*count = 1;\s*return true;\s*", body)
    if single:
        return description, [tag(single.group(1, 2, 3, 4))]
    listed = re.fullmatch(r"\s*/\*[^*]*\*/\s*unsigned int i;\s*hb_tag_t possible_tags\[\] = "
                          r"\{([^}]*)\};\s*for \(i = 0; i < (\d+) && i < \*count; i\+\+\)\s*"
                          r"tags\[i\] = possible_tags\[i\];\s*\*count = i;\s*return true;\s*", body)
    assert listed, f"unrecognised block {body!r}"
    tags = [tag(m) for m in re.findall(HB_TAG, listed.group(1))]
    return description, tags[:int(listed.group(2))]


def parse_complex(source):
    body = complex_function(source)
    guard = "  if (limit - lang_str >= 7)\n  {\n    const char *p = strchr (lang_str, '-');\n" \
            "    if (!p || p >= limit || limit - p < 5) goto out;\n"
    assert body.startswith(guard), "the variant guard changed"
    variants_end = body.index("\nout:\n")
    variants = body[len(guard):variants_end].rstrip()
    assert variants.endswith("}"), "unexpected end of the variant block"
    switch = body[variants_end + len("\nout:\n"):]
    assert switch.startswith("  switch (lang_str[0])\n  {\n"), "the switch changed"
    assert switch.rstrip().endswith("}\n  return false;"), "unexpected end of the switch"
    switch = switch[len("  switch (lang_str[0])\n  {\n"):switch.rstrip().rindex("}")]
    rules = []
    for case, condition, block in statements(variants[:-1]):
        assert case is None, "case label before the switch"
        rules.append((pattern(condition, None), *outcome(block)))
    letter = None
    for case, condition, block in statements(switch):
        letter = case or letter
        assert letter, "rule outside a case"
        rules.append((pattern(condition, letter), *outcome(block)))
    return rules


HEADER = """\
//! HarfBuzz's tables turning BCP 47 language tags into OpenType language
//! system tags, generated by `tools/gen_ot_language_tags.py` from HarfBuzz
//! 14.1.0's `src/hb-ot-tag-table.hh`
//! ({inputs}).
//! Do not edit by hand.
//!
//! HarfBuzz is distributed under the "Old MIT" license (SPDX
//! `MIT-Modern-Variant`); `hb-ot-tag.cc` carries this notice:
//!
{notice}
"""


def notice(tag_source):
    """The copyright and permission notice at the top of hb-ot-tag.cc."""
    block = re.match(r"/\*\n(.*?)\n \*/", tag_source, re.S).group(1)
    lines = [re.sub(r"^ \*(?: |$)", "", line) for line in block.splitlines()]
    end = next(i for i, line in enumerate(lines) if line.startswith("Red Hat Author"))
    while not lines[end - 1].strip():
        end -= 1
    return "\n".join(("//! > " + line).rstrip() for line in lines[:end])


def emit(source, tag_source):
    inputs = re.findall(r"^ \* (<meta name=\"updated_at\" content=\"([^\"]+)\" />|File-Date: (.+))$",
                        source, re.M)
    updated = next(m[1] for m in inputs if m[1])
    registry = next(m[2] for m in inputs if m[2])
    lines = [HEADER.format(
        inputs=f"OpenType language tags of {updated[:10]}, IANA subtag registry of {registry}",
        notice=notice(tag_source)).rstrip(), "",
        "use super::complex::{",
        "    ComplexLanguage,",
        "    Pattern::{Exact, Prefix, PrefixWithSubtag, Variant},",
        "};",
        "use crate::types::Tag;", ""]

    languages2 = parse_lang_tags(source, "ot_languages2", 2)
    lines += ["/// `ot_languages2`: two-letter languages and their tags, sorted by",
              "/// language; a language with several tags lists them in preference order.",
              "#[rustfmt::skip]",
              f"pub(super) static LANGUAGES2: [([u8; 2], Tag); {len(languages2)}] = ["]
    lines += [f'    (*b"{lang}", {rust_tag(t)}), // {c}' for lang, t, c in languages2]
    lines += ["];", ""]

    blocked = parse_blocked(source)
    lines += ["/// `ot_languages3_blocked`: three-letter languages whose upper-cased code",
              "/// is the tag of another language, so they get no tag at all; sorted.",
              "#[rustfmt::skip]",
              f"pub(super) static LANGUAGES3_BLOCKED: [[u8; 3]; {len(blocked)}] = ["]
    lines += [f'    *b"{lang}", // {c}' for lang, c in blocked]
    lines += ["];", ""]

    languages3 = parse_lang_tags(source, "ot_languages3", 3)
    lines += ["/// `ot_languages3`: three-letter languages with a single tag, sorted.",
              "#[rustfmt::skip]",
              f"pub(super) static LANGUAGES3: [([u8; 3], Tag); {len(languages3)}] = ["]
    lines += [f'    (*b"{lang}", {rust_tag(t)}), // {c}' for lang, t, c in languages3]
    lines += ["];", ""]

    multi = parse_multi(source)
    lines += ["/// `ot_languages3_multi`: three-letter languages with several tags, in",
              "/// preference order; sorted by language.",
              "#[rustfmt::skip]",
              f"pub(super) static LANGUAGES3_MULTI: [([u8; 3], &[Tag]); {len(multi)}] = ["]
    for lang, tags, c in multi:
        tags = ", ".join(rust_tag(t) for t in tags)
        lines.append(f'    (*b"{lang}", &[{tags}]), // {c}')
    lines += ["];", ""]

    rules = parse_complex(source)
    lines += ["/// `hb_ot_tags_from_complex_language`: languages recognised from several",
              "/// subtags, tried in order before the tables.",
              "#[rustfmt::skip]",
              f"pub(super) static COMPLEX_LANGUAGES: [ComplexLanguage; {len(rules)}] = ["]
    for rust_pattern, description, tags in rules:
        tags = ", ".join(rust_tag(t) for t in tags)
        lines.append(f"    // {description}")
        lines.append(f"    ComplexLanguage::new({rust_pattern}, &[{tags}]),")
    lines += ["];"]
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_ot_language_tags.py HARFBUZZ_SRC_DIR")
    directory = pathlib.Path(sys.argv[1])
    source = (directory / "hb-ot-tag-table.hh").read_text(encoding="utf-8")
    tag_source = (directory / "hb-ot-tag.cc").read_text(encoding="utf-8")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(source, tag_source), encoding="utf-8")


if __name__ == "__main__":
    main()
