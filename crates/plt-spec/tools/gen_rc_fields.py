"""Generate crates/plt-spec/src/probes/areas/rcsetup/fields.rs from the rc
table: the canonical value of each parameter, looked up by key.

Run after regenerating crates/plt/src/rc/table.rs:
    python3 -I crates/plt-spec/tools/gen_rc_fields.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
TABLE = ROOT / "crates" / "plt" / "src" / "rc" / "table.rs"
OUT = ROOT / "crates" / "plt-spec" / "src" / "probes" / "areas" / "rcsetup" / "fields.rs"

# Keys the rcsetup probes leave out (see spec/reference/probes/test_rcsetup.py).
SKIP = {"path.effects"}

ENTRY = re.compile(r"^\s+([a-z0-9_]+): .*=> \"([^\"]+)\"")


def main():
    entries = [m.groups() for m in map(ENTRY.match, TABLE.read_text().splitlines()) if m]
    arms = [f'        "{key}" => rc.{field}.canon(),' for field, key in entries if key not in SKIP]
    lines = [
        "//! The canonical value of every probed rcParam, by key.",
        "//!",
        "//! Generated by `crates/plt-spec/tools/gen_rc_fields.py` from",
        "//! `crates/plt/src/rc/table.rs`; do not edit by hand.",
        "",
        "use plt::rc::RcParams;",
        "",
        "use super::canon::Canon;",
        "use crate::json::Json;",
        "",
        "/// The canonical value of the parameter `key` in `rc`, if it is probed.",
        "#[allow(clippy::too_many_lines, reason = \"generated: one arm per rcParam\")]",
        "pub(super) fn canonical(rc: &RcParams, key: &str) -> Option<Json> {",
        "    Some(match key {",
        *arms,
        "        _ => return None,",
        "    })",
        "}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(arms)} parameters to {OUT}")


if __name__ == "__main__":
    main()
