"""Generate the mathtext symbol tables of plt_text::mathtext::data.

Run with the reference venv, then format:

    .venv/bin/python -I crates/plt-text/tools/gen_mathtext_data.py && cargo fmt -p plt-text

Writes crates/plt-text/src/mathtext/data/{tex2uni,bakoma,stix,symbols,unicode}.rs
(committed). The tables are copied from matplotlib's `_mathtext_data.py`
(`tex2uni`, `latex_to_bakoma`, `stix_virtual_fonts`) and from the symbol
classes of `_mathtext.Parser` and `_mathtext.BakomaFonts`; the Unicode
tables reproduce the `unicodedata` / `str` predicates mathtext relies on.
"""

import pathlib
import sys
import unicodedata

from matplotlib import _mathtext
from matplotlib._mathtext_data import latex_to_bakoma, stix_virtual_fonts, tex2uni

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "mathtext" / "data"
HEADER = """//! {what}
//!
//! Generated by `crates/plt-text/tools/gen_mathtext_data.py` from
//! matplotlib {version}. Do not edit by hand.
"""

FONT_NAMES = {
    "rm": "Rm", "it": "It", "bf": "Bf", "bfit": "Bfit", "sf": "Sf", "tt": "Tt",
    "cal": "Cal", "ex": "Ex", "default": "Default", "regular": "Regular",
    "normal": "Normal", "bb": "Bb", "frak": "Frak", "scr": "Scr",
}


def rs_str(text):
    out = []
    for c in text:
        if c in '\\"':
            out.append("\\" + c)
        elif " " <= c <= "~":
            out.append(c)
        else:
            out.append(f"\\u{{{ord(c):x}}}")
    return '"' + "".join(out) + '"'


def font_name(name):
    return "FontName::" + FONT_NAMES[name]


def header(what):
    import matplotlib

    return HEADER.format(what=what, version=matplotlib.__version__)


def write(name, text):
    (OUT / name).write_text(text)


def str_list(name, doc, items):
    items = sorted(items)
    body = "".join(f"    {rs_str(item)},\n" for item in items)
    return f"/// {doc}\npub(crate) static {name}: [&str; {len(items)}] = [\n{body}];\n"


def gen_tex2uni():
    items = sorted(tex2uni.items())
    body = "".join(f"    ({rs_str(k)}, 0x{v:x}),\n" for k, v in items)
    write(
        "tex2uni.rs",
        header("matplotlib's `tex2uni`: TeX symbol names (without the backslash) to\n"
               "//! Unicode code points, sorted by name.")
        + f"\npub(crate) static TEX2UNI: [(&str, u32); {len(items)}] = [\n{body}];\n",
    )


def gen_bakoma():
    files = {"cmex10": "Cmex10", "cmmi10": "Cmmi10", "cmr10": "Cmr10",
             "cmsy10": "Cmsy10", "cmtt10": "Cmtt10"}
    items = sorted(latex_to_bakoma.items())
    body = "".join(
        f"    ({rs_str(k)}, BakomaFile::{files[f]}, 0x{c:x}),\n" for k, (f, c) in items)
    alts = sorted(_mathtext.BakomaFonts._size_alternatives.items())
    alt_body = "".join(
        f"    ({rs_str(sym)}, &[{', '.join(f'({font_name(f)}, {rs_str(s)})' for f, s in alt)}]),\n"
        for sym, alt in alts)
    write(
        "bakoma.rs",
        header("The `BaKoMa` Computer Modern tables: matplotlib's `latex_to_bakoma` and\n"
               "//! `BakomaFonts._size_alternatives`, sorted by symbol.")
        + "\nuse super::BakomaFile;\nuse crate::mathtext::font_name::FontName;\n\n"
        + "/// Symbol to `(font file, character code)`.\n"
        + f"pub(crate) static LATEX_TO_BAKOMA: [(&str, BakomaFile, u32); {len(items)}] = [\n"
        + body + "];\n\n"
        + "/// Delimiters with pre-sized alternatives, smallest first.\n"
        + f"pub(crate) static SIZE_ALTERNATIVES: [(&str, &[(FontName, &str)]); {len(alts)}] = [\n"
        + alt_body + "];\n",
    )


def ranges_rs(ranges):
    return "".join(
        f"    VirtualRange::new(0x{a:x}, 0x{b:x}, {font_name(f)}, 0x{d:x}),\n"
        for a, b, f, d in ranges)


def gen_stix():
    out = [header("matplotlib's `stix_virtual_fonts`: alphabets that live at other code\n"
                  "//! points (double-struck, script, fraktur, sans-serif, monospace).")]
    out.append("\nuse super::{VirtualFont, VirtualRange};\nuse crate::mathtext::font_name::FontName;\n")
    entries = []
    for name, value in sorted(stix_virtual_fonts.items()):
        if isinstance(value, dict):
            classes = []
            for cls, ranges in value.items():
                const = f"{name.upper()}_{cls.upper()}"
                out.append(f"\nstatic {const}: [VirtualRange; {len(ranges)}] = [\n"
                           f"{ranges_rs(ranges)}];\n")
                classes.append(f"({font_name(cls)}, &{const})")
            entries.append((name, f"VirtualFont::ByClass(&[{', '.join(classes)}])"))
        else:
            const = name.upper()
            out.append(f"\nstatic {const}: [VirtualRange; {len(value)}] = [\n"
                       f"{ranges_rs(value)}];\n")
            entries.append((name, f"VirtualFont::Single(&{const})"))
    body = "".join(f"    ({font_name(n)}, {v}),\n" for n, v in entries)
    out.append("\n/// The virtual fonts by TeX font name.\n"
               f"pub(crate) static VIRTUAL_FONTS: [(FontName, VirtualFont); {len(entries)}] = [\n"
               f"{body}];\n")
    write("stix.rs", "".join(out))


def gen_symbols():
    P = _mathtext.Parser
    out = [header("The symbol classes of matplotlib's mathtext parser (`_mathtext.Parser`).")]
    out.append("\n")
    out.append(str_list("BINARY_OPERATORS", "Binary operators (spaced unless unary).",
                        P._binary_operators))
    out.append(str_list("RELATION_SYMBOLS", "Relations (always spaced).", P._relation_symbols))
    out.append(str_list("ARROW_SYMBOLS", "Arrows (always spaced).", P._arrow_symbols))
    out.append(str_list("PUNCTUATION_SYMBOLS", "Punctuation (followed by a space).",
                        P._punctuation_symbols))
    out.append(str_list("OVERUNDER_SYMBOLS", "Big operators with limits above and below.",
                        P._overunder_symbols))
    out.append(str_list("OVERUNDER_FUNCTIONS", "Function names with limits above and below.",
                        P._overunder_functions))
    out.append(str_list("DROPSUB_SYMBOLS", "Integrals, whose scripts drop.", P._dropsub_symbols))
    out.append(str_list("FONT_NAMES", "Font switches (`\\rm`, `\\mathrm{...}`).", P._fontnames))
    out.append(str_list("FUNCTION_NAMES", "Named functions (`\\sin`, `\\lim`, ...).",
                        P._function_names))
    out.append(str_list("LEFT_DELIMS", "Opening delimiters.", P._left_delims))
    out.append(str_list("RIGHT_DELIMS", "Closing delimiters.", P._right_delims))
    out.append(str_list("AMBI_DELIMS", "Delimiters that both open and close.", P._ambi_delims))
    out.append(str_list("SMALL_GREEK", "Names of the lowercase Greek letters.", P._small_greek))
    out.append(str_list("WIDE_ACCENTS", "Accents stretched to the accented width.",
                        P._wide_accents))
    spaces = sorted(P._space_widths.items())
    out.append("/// Spacing commands and their width in em.\n"
               f"pub(crate) static SPACE_WIDTHS: [(&str, f64); {len(spaces)}] = [\n"
               + "".join(f"    ({rs_str(k)}, {float(v)!r}),\n" for k, v in spaces) + "];\n")
    accents = sorted(P._accent_map.items())
    out.append("/// Accent commands and the symbol drawn for them.\n"
               f"pub(crate) static ACCENT_MAP: [(&str, &str); {len(accents)}] = [\n"
               + "".join(f"    ({rs_str(k)}, {rs_str(v)}),\n" for k, v in accents) + "];\n")
    write("symbols.rs", "\n".join(out))


def char_ranges(predicate, limit):
    ranges = []
    start = None
    for code in range(limit + 1):
        if predicate(chr(code)) if code <= 0x10FFFF else False:
            if start is None:
                start = code
        elif start is not None:
            ranges.append((start, code - 1))
            start = None
    if start is not None:
        ranges.append((start, limit))
    return ranges


def ranges_table(name, doc, ranges):
    body = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in ranges)
    return f"/// {doc}\npub(crate) static {name}: [(u32, u32); {len(ranges)}] = [\n{body}];\n"


def gen_unicode():
    letters = char_ranges(lambda c: unicodedata.category(c)[0] == "L", 0xFFFF)
    greek_capital = char_ranges(
        lambda c: unicodedata.name(c, "").startswith("GREEK CAPITAL"), 0xFFFF)
    digits = char_ranges(str.isdigit, 0x10FFFF)
    spaces = char_ranges(str.isspace, 0x10FFFF)
    out = [header(f"Unicode {unicodedata.unidata_version} character classes as Python's "
                  "`unicodedata` and `str`\n//! methods report them (inclusive ranges).")]
    out.append("\n")
    out.append(ranges_table("LETTERS", "BMP characters of general category `L*`.", letters))
    out.append(ranges_table("GREEK_CAPITALS",
                            "BMP characters whose name starts with `GREEK CAPITAL`.",
                            greek_capital))
    out.append(ranges_table("DIGITS", "Characters for which `str.isdigit` holds.", digits))
    out.append(ranges_table("SPACES", "Characters for which `str.isspace` holds.", spaces))
    write("unicode.rs", "\n".join(out))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    gen_tex2uni()
    gen_bakoma()
    gen_stix()
    gen_symbols()
    gen_unicode()
    return 0


if __name__ == "__main__":
    sys.exit(main())
