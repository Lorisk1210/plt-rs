"""Generate the tables of plt::colors::multivar.

Run with the reference venv, then format:

    .venv/bin/python -I crates/plt/tools/gen_multivar.py
    rustfmt --edition 2024 crates/plt/src/colors/multivar/data.rs

Writes crates/plt/src/colors/multivar/data.rs (committed): matplotlib's
multivariate colormap colours from `_cm_multivar.py` and the bivariate RGB
grids from `_cm_bivar.py`, as RGB triples one after the other. plt-rs builds
the colormaps from them the way matplotlib does.
"""

import pathlib

import numpy as np
from matplotlib import _cm_bivar, _cm_multivar

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "colors" / "multivar" / "data.rs"
HEADER = """//! The colours of matplotlib's multivariate and bivariate colormaps, as RGB
//! triples one after the other.
//!
//! Generated by `crates/plt/tools/gen_multivar.py` from matplotlib's
//! `_cm_multivar.py` and `_cm_bivar.py`. Do not edit by hand.

#![allow(clippy::approx_constant, reason = "exact floats copied from matplotlib")]
"""

TABLES = [
    ("BI_PEAK", _cm_bivar.BiPeak, "`BiPeak`: a 65 × 65 grid, row-major."),
    ("BI_ORANGE_BLUE", _cm_bivar.BiOrangeBlue, "`BiOrangeBlue`: a 2 × 2 grid, row-major."),
] + [
    ("VAR" + name[0] + "_" + name[1:].replace("Var", "").upper(),
     getattr(_cm_multivar, f"_{name}_data"),
     f"The colours of `{name}`, evenly spaced.")
    for name in ["2VarAddA0", "2VarAddA1", "2VarSubA0", "2VarSubA1",
                 "3VarAddA0", "3VarAddA1", "3VarAddA2"]
]


def table(name, values, doc):
    values = np.asarray(values, float).ravel()
    body = " ".join(f"{v:.3f}," for v in values)
    return f"/// {doc}\npub(super) const {name}: &[f64] = &[{body}];\n"


def main():
    OUT.write_text(HEADER + "\n" + "\n".join(table(*t) for t in TABLES))


if __name__ == "__main__":
    main()
