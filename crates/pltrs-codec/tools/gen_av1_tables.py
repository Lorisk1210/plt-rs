"""Generate the AV1 encoder's constant tables in src/av1/tables/ from the
AV1 Bitstream & Decoding Process Specification (the Markdown sources of
https://github.com/AOMediaCodec/av1-spec, section "Additional tables"):

* ``mode_cdfs.rs``: the default CDFs of the intra frame mode info the
  encoder writes (luma and chroma modes, angle deltas, partitions, skip
  and the reduced intra transform set);
* ``palette_cdfs.rs``: the default CDFs of palette mode (whether a block
  uses a palette, its size and the colour indices);
* ``coeff_cdfs.rs``: the default CDFs of coefficient coding, for the four
  quantizer contexts (without the end-of-block classes of rectangular
  transforms, which the encoder does not use);
* ``lookup.rs``: the 8-bit rows of the DC and AC quantizer lookups and the
  smooth prediction weights.

A CDF of N symbols becomes an array of N values: its first N - 1
cumulative probabilities (the specification's final 32768 is implied)
and the adaptation counter, which starts at 0. Pass the unpacked
specification directory:

    curl -sSL -o av1-spec.tar.gz https://codeload.github.com/AOMediaCodec/av1-spec/tar.gz/refs/heads/master
    tar xf av1-spec.tar.gz
    python3 -I crates/pltrs-codec/tools/gen_av1_tables.py av1-spec-master
"""

