import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "av1" / "tables"

HEADER = """//! {what}.
//!
//! Generated by `tools/gen_av1_tables.py` from the AV1 Bitstream &
//! Decoding Process Specification, section "Additional tables". Do not
//! edit by hand. The specification is copyright the Alliance for Open
//! Media."""

