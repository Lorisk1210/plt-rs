def table(text, name):
    """The dimensions and flat values of the C table `name`."""
    match = re.search(re.escape(name) + r"((?:\s*\[[^\]]*\])+)\s*=\s*\{", text)
    if match is None:
        sys.exit(f"table {name} not found")
    depth, pos = 1, match.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[pos], 0)
        pos += 1
    body = text[match.end():pos - 1]
    dims = re.findall(r"\[([^\]]*)\]", match.group(1))
    tokens = [t.strip() for t in re.split(r"[{},]", body)]
    return dims, [value(t) for t in tokens if t]


def value(token):
    """An integer entry, written as a number or a product of two."""
    product = re.fullmatch(r"(\d+)\s*\*\s*(\d+)", token)
    if product:
        return int(product.group(1)) * int(product.group(2))
    if not re.fullmatch(r"-?\d+", token):
        sys.exit(f"cannot read table entry {token!r}")
    return int(token)


CONSTANTS = {
    "INTRA_MODE_CONTEXTS": 5, "INTRA_MODES": 13, "UV_INTRA_MODES_CFL_NOT_ALLOWED": 13,
    "UV_INTRA_MODES_CFL_ALLOWED": 14, "DIRECTIONAL_MODES": 8, "MAX_ANGLE_DELTA": 3,
    "PARTITION_CONTEXTS": 4, "SKIP_CONTEXTS": 3, "COEFF_CDF_Q_CTXS": 4, "TX_SIZES": 5,
    "TXB_SKIP_CONTEXTS": 13, "PLANE_TYPES": 2, "EOB_COEF_CONTEXTS": 9,
    "DC_SIGN_CONTEXTS": 3, "SIG_COEF_CONTEXTS_EOB": 4, "SIG_COEF_CONTEXTS": 42,
    "LEVEL_CONTEXTS": 21, "DELTA_Q_SMALL": 3, "PALETTE_BLOCK_SIZE_CONTEXTS": 7,
    "PALETTE_Y_MODE_CONTEXTS": 3, "PALETTE_UV_MODE_CONTEXTS": 2, "PALETTE_SIZES": 7,
    "PALETTE_COLOR_CONTEXTS": 5, "BR_CDF_SIZE": 4,
}


def eval_dim(expr):
    expr = expr.strip()
    for key, value in sorted(CONSTANTS.items(), key=lambda kv: -len(kv[0])):
        expr = expr.replace(key, str(value))
    if not re.fullmatch(r"[\d\s+*()-]+", expr):
        sys.exit(f"cannot evaluate dimension {expr}")
    return eval(expr)


def nest(values, dims):
    """`values` split into nested lists of shape `dims`."""
    if len(dims) == 1:
        return values
    step = len(values) // dims[0]
    return [nest(values[i:i + step], dims[1:]) for i in range(0, len(values), step)]


def render(name, doc, dims, leaf, data):
    """A Rust constant of CDF rows nested as `dims`, rows packed into lines."""
    rust_type = f"[u16; {leaf}]"
    for dim in reversed(dims):
        rust_type = f"[{rust_type}; {dim}]"
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub(crate) const {name}: {rust_type} = ["]

    def emit(node, indent):
        pad = "    " * indent
        if isinstance(node[0][0], int):
            line = pad
            for cdf in node:
                item = "[" + ", ".join(str(v) for v in cdf) + "],"
                if len(line) + len(item) + 1 > 100 and line.strip():
                    lines.append(line.rstrip())
                    line = pad
                line += item + " "
            lines.append(line.rstrip())
            return
        for child in node:
            lines.append(pad + "[")
            emit(child, indent + 1)
            lines.append(pad + "],")

    if dims:
        emit(data, 1)
    else:
        lines.append("    " + ", ".join(str(v) for v in data[0]) + ",")
    lines.append("];")
    return "\n".join(lines)


def cdf_const(text, rust_name, spec_name, doc):
    dims, values = table(text, spec_name)
    shape = [eval_dim(d) for d in dims]
    row = shape[-1]
    if len(values) != _product(shape):
        sys.exit(f"{spec_name}: {len(values)} values for shape {shape}")
    rows = [values[i:i + row] for i in range(0, len(values), row)]
    for cdf in rows:
        if cdf[-2:] != [32768, 0]:
            sys.exit(f"{spec_name}: malformed CDF {cdf}")
    leaves = [cdf[:-2] + [0] for cdf in rows]
    outer = shape[:-1]
    data = nest(leaves, outer) if len(outer) > 1 else leaves
    return render(rust_name, doc, outer, row - 1, data)


def _product(shape):
    total = 1
    for dim in shape:
        total *= dim
    return total


def lookup_const(rust_name, doc, values, kind):
    lines = [f"/// {doc}", "#[rustfmt::skip]",
             f"pub(crate) const {rust_name}: [{kind}; {len(values)}] = ["]
    line = "   "
    for value in values:
        item = f" {value},"
        if len(line) + len(item) > 100:
            lines.append(line)
            line = "   "
        line += item
    lines.append(line)
    lines.append("];")
    return "\n".join(lines)


def main():
    spec = pathlib.Path(sys.argv[1])
    tables_text = (spec / "10.additional.tables.md").read_text()
    decoding_text = (spec / "08.decoding.process.md").read_text()
    OUT.mkdir(parents=True, exist_ok=True)

    parts = [HEADER.format(what="The default CDFs of intra mode info")]
    parts += [cdf_const(tables_text, *entry) for entry in MODE_CDFS]
    (OUT / "mode_cdfs.rs").write_text("\n\n".join(parts) + "\n")

    parts = [HEADER.format(what="The default CDFs of palette mode")]
    parts += [cdf_const(tables_text, *entry) for entry in PALETTE_CDFS]
    (OUT / "palette_cdfs.rs").write_text("\n\n".join(parts) + "\n")

    parts = [HEADER.format(what="The default CDFs of coefficient coding")]
    parts += [cdf_const(tables_text, *entry) for entry in COEFF_CDFS]
    (OUT / "coeff_cdfs.rs").write_text("\n\n".join(parts) + "\n")

    parts = [HEADER.format(what="The quantizer lookups and smooth prediction weights")]
    for rust_name, spec_name, doc in [
        ("DC_QLOOKUP", "Dc_Qlookup", "The DC quantizer of each quantizer index, at 8 bits."),
        ("AC_QLOOKUP", "Ac_Qlookup", "The AC quantizer of each quantizer index, at 8 bits."),
    ]:
        _, values = table(decoding_text, spec_name)
        parts.append(lookup_const(rust_name, doc, values[:256], "u16"))
    for size in (4, 8, 16, 32, 64):
        _, values = table(tables_text, f"Sm_Weights_Tx_{size}x{size}")
        parts.append(lookup_const(f"SM_WEIGHTS_{size}",
                                  f"The smooth prediction weights of {size}-sample edges.",
                                  values, "u16"))
    (OUT / "lookup.rs").write_text("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
