//! `afmFontProperty` reads them from the metrics files.

use super::afm::{AfmDirectory, AfmFont};
use crate::db::query::{FontStyle, Stretch};

const fn afm(
    file: &'static str,
    name: &'static str,
    style: FontStyle,
    weight: &'static str,
    stretch: Stretch,
    directory: AfmDirectory,
) -> AfmFont {
    AfmFont {
        file,
        name,
        style,
        weight,
        stretch,
        directory,
    }
}

