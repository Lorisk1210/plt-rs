"""Generate the autohinter's data tables in src/autofit/tables/ from the
FreeType 2.14.3 sources matplotlib 3.11 bundles:

* ``scripts.rs``: the scripts of ``afscript.h`` (HarfBuzz script, hinting
  direction, standard characters, Unicode ranges) and the styles of
  ``afstyles.h`` (writing system, script, blue zones, coverage), in
  FreeType's order;
* ``blues.rs``: the blue zone strings and string sets of ``afblue.dat``;
* ``ranges.rs``: the script and non-base character ranges of ``afranges.c``;
* ``adjustments.rs``: the diacritic adjustment database of ``afadjust.c``
  (in FreeType's order, which is not quite sorted).

FreeType is configured as matplotlib builds it: ``AF_CONFIG_OPTION_CJK``
and ``AF_CONFIG_OPTION_INDIC`` on, ``AF_CONFIG_OPTION_CJK_BLUE_HANI_VERT``
off.  Pass the unpacked FreeType source directory:

    curl -sSLO https://download.savannah.gnu.org/releases/freetype/freetype-2.14.3.tar.xz
    tar xf freetype-2.14.3.tar.xz
    python3 -I crates/pltrs-font/tools/gen_autofit_tables.py freetype-2.14.3
"""

import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "autofit" / "tables"

# Preprocessor symbols as matplotlib's FreeType build defines them.
DEFINED = {"AF_CONFIG_OPTION_CJK": True, "AF_CONFIG_OPTION_INDIC": True,
           "AF_CONFIG_OPTION_CJK_BLUE_HANI_VERT": False}

HEADER = """//! {what}, generated by `tools/gen_autofit_tables.py`
//! from FreeType 2.14.3's `src/autofit/{source}`. Do not edit by hand.
//!
//! FreeType is copyright David Turner, Robert Wilhelm and Werner Lemberg,
//! distributed under the FreeType License (FTL).
"""


def preprocess(text):
    """Keeps the lines of `text` whose #ifdef / #if 0 conditions hold."""
    out, stack = [], []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#ifdef"):
            stack.append(DEFINED.get(stripped.split()[1], False))
        elif stripped.startswith("#ifndef"):
            stack.append(not DEFINED.get(stripped.split()[1], False))
        elif stripped.startswith("#if"):
            stack.append(stripped.split()[1] != "0")
        elif stripped.startswith("#else"):
            stack[-1] = not stack[-1]
        elif stripped.startswith("#endif"):
            stack.pop()
        elif all(stack):
            out.append(line)
    return "\n".join(out)


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def c_string(literals):
    """Decodes concatenated C string literals (with \\xNN escapes)."""
    data = bytearray()
    for literal in re.findall(r'"((?:[^"\\]|\\.)*)"', literals):
        i = 0
        while i < len(literal):
            if literal[i] == "\\":
                if literal[i + 1] == "x":
                    data.append(int(literal[i + 2:i + 4], 16))
                    i += 4
                    continue
                data.append(ord({"n": "\n", "t": "\t", "\\": "\\", '"': '"'}[literal[i + 1]]))
                i += 2
                continue
            data.extend(literal[i].encode())
            i += 1
    return data.decode("utf-8")


def rust_string(text):
    """A Rust string literal, non-ASCII characters escaped."""
    out = []
    for c in text:
        if c in '"\\':
            out.append("\\" + c)
        elif ord(c) < 0x80:
            out.append(c)
        else:
            out.append("\\u{%X}" % ord(c))
    return '"' + "".join(out) + '"'


def comment_text(text):
    """The characters of `text` for a trailing comment (marks shown on a
    dotted circle)."""
    import unicodedata
    return "".join("◌" + c if unicodedata.combining(c) or
                   unicodedata.category(c) in ("Mn", "Me") else c for c in text)


def hb_scripts(autofit):
    text = (autofit / "hb-script-list.h").read_text()
    scripts = {}
    for name, a, b, c, d in re.findall(
            r"(HB_SCRIPT_\w+)\s*=\s*HB_TAG\s*\('(.)','(.)','(.)','(.)'\)", text):
        scripts[name] = a + b + c + d
    scripts["HB_SCRIPT_INVALID"] = None
    return scripts


def parse_scripts(autofit):
    text = preprocess((autofit / "afscript.h").read_text())
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    pattern = re.compile(
        r'SCRIPT\(\s*(\w+),\s*(\w+),\s*"[^"]*",\s*(HB_SCRIPT_\w+),\s*'
        r'(HINTING_\w+),\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\)')
    return [(s, S, h, d == "HINTING_TOP_TO_BOTTOM", c_string(chars))
            for s, S, h, d, chars in pattern.findall(text)]


def parse_styles(autofit):
    text = strip_comments(preprocess((autofit / "afstyles.h").read_text()))
    text = re.sub(r"#(?:undef|define)(?:[^\n\\]|\\\n|\\.)*", "", text)
    meta = [("c2cp", "PETITE_CAPITALS_FROM_CAPITALS"),
            ("c2sc", "SMALL_CAPITALS_FROM_CAPITALS"), ("ordn", "ORDINALS"),
            ("pcap", "PETITE_CAPITALS"), ("sinf", "SCIENTIFIC_INFERIORS"),
            ("smcp", "SMALL_CAPITALS"), ("subs", "SUBSCRIPT"),
            ("sups", "SUPERSCRIPT"), ("titl", "TITLING"), ("dflt", "DEFAULT")]
    styles = []
    token = re.compile(
        r'(META_STYLE_LATIN|STYLE_DEFAULT_INDIC|STYLE)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)')
    for kind, args in token.findall(text):
        parts = [p.strip() for p in re.split(r",(?=(?:[^\"]*\"[^\"]*\")*[^\"]*$)", args)]
        if kind == "STYLE":
            name, _, _, ws, script, blues, coverage = parts
            styles.append((name, ws.removeprefix("AF_WRITING_SYSTEM_"),
                           script.removeprefix("AF_SCRIPT_"),
                           None if blues.startswith("(") else
                           blues.removeprefix("AF_BLUE_STRINGSET_"),
                           coverage.removeprefix("AF_COVERAGE_")))
        elif kind == "META_STYLE_LATIN":
            s, S, _ = parts
            for feature, coverage in meta:
                styles.append((f"{s}_{feature}", "LATIN", S, S, coverage))
        else:
            s, S, _ = parts
            styles.append((f"{s}_dflt", "INDIC", S, None, "DEFAULT"))
    return styles


def parse_blues(autofit):
    text = preprocess((autofit / "afblue.dat").read_text())
    text = re.sub(r"//[^\n]*", "", text)
    strings_part, sets_part = text.split("AF_BLUE_STRINGSET_ENUM")
    strings = {}
    for name, literals in re.findall(
            r"AF_BLUE_STRING_(\w+)\s+((?:\"[^\"]*\"\s*)+)", strings_part):
        strings[name] = c_string(literals)
    sets = {}
    for name, body in re.findall(
            r"AF_BLUE_STRINGSET_(\w+)\s+((?:\{[^}]*\}\s*)+)", sets_part):
        entries = []
        for string, props in re.findall(r"\{\s*AF_BLUE_STRING_(\w+)\s*,\s*([^}]*)\}", body):
            if string == "MAX":
                break
            flags = [p.strip().removeprefix("AF_BLUE_PROPERTY_")
                     for p in props.split("|") if p.strip() != "0"]
            entries.append((string, flags))
        sets[name] = entries
    return strings, sets


def parse_ranges(autofit):
    text = strip_comments(preprocess((autofit / "afranges.c").read_text()))
    ranges = {}
    for name, body in re.findall(
            r"af_(\w+)_uniranges\[\]\s*=\s*\{(.*?)\};", text, flags=re.S):
        pairs = [(int(a, 16 if a.lower().startswith("0x") else 10),
                  int(b, 16 if b.lower().startswith("0x") else 10))
                 for a, b in re.findall(r"AF_UNIRANGE_REC\(\s*(\w+),\s*(\w+)\s*\)", body)]
        ranges[name] = [p for p in pairs if p != (0, 0)]
    return ranges


def parse_adjustments(autofit):
    text = preprocess((autofit / "afadjust.c").read_text())
    body = text.split("adjustment_database[] =")[1].split("};")[0]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    entries = []
    for code, flags in re.findall(r"\{\s*(0x[0-9A-Fa-f]+),\s*([^}]*)\}", body):
        names = [f.strip() for f in flags.split("|")]
        entries.append((int(code, 16), names))
    return entries


def emit_blues(strings, sets):
    lines = [HEADER.format(what="Blue zone strings", source="afblue.dat"),
             "use super::{BlueString, blue};", ""]
    used = {string for entries in sets.values() for string, _ in entries}
    for name, text in strings.items():
        if name not in used:
            continue
        lines.append(f"/// {comment_text(text)}")
        lines.append("#[rustfmt::skip]")
        lines.append(f"const {name}: &str = {rust_string(text)};")
    lines.append("")
    for name, entries in sets.items():
        lines.append(f"/// The blue zones of the `{name.lower()}` styles.")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(crate) const {name}: &[BlueString] = &[")
        for string, flags in entries:
            props = " | ".join("blue::" + f for f in flags) if flags else "0"
            lines.append(f"    BlueString::new({string}, {props}),")
        lines.append("];")
    return "\n".join(lines) + "\n"


def emit_ranges(ranges):
    lines = [HEADER.format(what="Unicode ranges of the autohinter's scripts",
                           source="afranges.c"),
             "use super::UniRange;", ""]
    for name, pairs in ranges.items():
        const = name.upper()
        lines.append(f"/// `af_{name}_uniranges`.")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(crate) const {const}: &[UniRange] = &[")
        for i in range(0, len(pairs), 4):
            chunk = pairs[i:i + 4]
            lines.append("    " + " ".join(f"(0x{a:04X}, 0x{b:04X})," for a, b in chunk))
        lines.append("];")
    return "\n".join(lines) + "\n"


def emit_scripts(scripts, styles, hb, sets):
    lines = [HEADER.format(what="Scripts and styles of the autohinter",
                           source="afscript.h` and `afstyles.h"),
             "use super::{Coverage, ScriptClass, StyleClass, WritingSystem, blues, ranges};",
             "use crate::types::Tag;", ""]
    index = {S: i for i, (_, S, _, _, _) in enumerate(scripts)}
    lines.append("/// Index of each script in [`SCRIPTS`].")
    lines.append("mod script {")
    for s, S, _, _, _ in scripts:
        lines.append(f"    pub(super) const {S}: usize = {index[S]};")
    lines.append("}")
    lines.append("")
    lines.append("/// The script whose default features cover glyphs no script claims")
    lines.append("/// (`AF_SCRIPT_DEFAULT`).")
    lines.append("pub(crate) const DEFAULT_SCRIPT: usize = script::LATN;")
    lines.append("")
    lines.append(f"/// FreeType's scripts (`af_script_classes`), in its order.")
    lines.append("#[rustfmt::skip]")
    lines.append(f"pub(crate) static SCRIPTS: [ScriptClass; {len(scripts)}] = [")
    for s, S, h, top_to_bottom, chars in scripts:
        tag = hb[h]
        tag = f'Some(Tag::new(b"{tag}"))' if tag else "None"
        lines.append(f"    // {S.lower()}: {comment_text(chars)}".rstrip())
        lines.append(f"    ScriptClass::new({tag}, {str(top_to_bottom).lower()}, "
                     f"{rust_string(chars)},")
        lines.append(f"        ranges::{s.upper()}, ranges::{s.upper()}_NONBASE),")
    lines.append("];")
    lines.append("")
    coverage_names = {
        "PETITE_CAPITALS_FROM_CAPITALS": "PetiteCapitalsFromCapitals",
        "SMALL_CAPITALS_FROM_CAPITALS": "SmallCapitalsFromCapitals",
        "ORDINALS": "Ordinals", "PETITE_CAPITALS": "PetiteCapitals", "RUBY": "Ruby",
        "SCIENTIFIC_INFERIORS": "ScientificInferiors", "SMALL_CAPITALS": "SmallCapitals",
        "SUBSCRIPT": "Subscript", "SUPERSCRIPT": "Superscript", "TITLING": "Titling",
        "DEFAULT": "Default"}
    ws_names = {"DUMMY": "Dummy", "LATIN": "Latin", "CJK": "Cjk", "INDIC": "Indic"}
    for i, style in enumerate(styles):
        if style[0] == "hani_dflt":
            fallback = i
        if style[0] == "none_dflt":
            none = i
    lines.append("/// The style of glyphs no script or feature covers")
    lines.append("/// (`AF_STYLE_FALLBACK`, CJK ideographs).")
    lines.append(f"pub(crate) const FALLBACK_STYLE: usize = {fallback};")
    lines.append("/// The unhinted style (`AF_STYLE_NONE_DFLT`).")
    lines.append(f"pub(crate) const NONE_STYLE: usize = {none};")
    lines.append("")
    lines.append(f"/// FreeType's styles (`af_style_classes`), in its order.")
    lines.append("#[rustfmt::skip]")
    lines.append(f"pub(crate) static STYLES: [StyleClass; {len(styles)}] = [")
    for name, ws, script, blue_set, coverage in styles:
        blue = f"blues::{blue_set}" if blue_set is not None else "&[]"
        lines.append(f"    StyleClass::new(WritingSystem::{ws_names[ws]}, script::{script}, "
                     f"{blue}, Coverage::{coverage_names[coverage]}), // {name}")
    lines.append("];")
    return "\n".join(lines) + "\n"


def emit_adjustments(entries):
    flag_names = {
        "AF_ADJUST_UP": "UP", "AF_ADJUST_DOWN": "DOWN", "AF_ADJUST_UP2": "UP2",
        "AF_ADJUST_DOWN2": "DOWN2", "AF_ADJUST_TILDE_TOP": "TILDE_TOP",
        "AF_ADJUST_TILDE_BOTTOM": "TILDE_BOTTOM", "AF_ADJUST_TILDE_TOP2": "TILDE_TOP2",
        "AF_ADJUST_TILDE_BOTTOM2": "TILDE_BOTTOM2",
        "AF_IGNORE_CAPITAL_TOP": "IGNORE_CAPITAL_TOP",
        "AF_IGNORE_CAPITAL_BOTTOM": "IGNORE_CAPITAL_BOTTOM",
        "AF_IGNORE_SMALL_TOP": "IGNORE_SMALL_TOP",
        "AF_IGNORE_SMALL_BOTTOM": "IGNORE_SMALL_BOTTOM",
        "AF_ADJUST_NO_HEIGHT_CHECK": "NO_HEIGHT_CHECK"}
    used = sorted({flag_names[n] for _, names in entries for n in names},
                  key=list(flag_names.values()).index)
    lines = [HEADER.format(what="The diacritic adjustment database",
                           source="afadjust.c"),
             "use super::adjust::{", "    " + ", ".join(used[:5]) + ",",
             "    " + ", ".join(used[5:]) + ",", "};", "",
             "/// Code points and their adjustment flags, in FreeType's order",
             "/// (`adjustment_database`; FreeType's binary search depends on it).",
             "#[rustfmt::skip]",
             f"pub(crate) static ADJUSTMENTS: [(u32, u16); {len(entries)}] = ["]
    for code, names in entries:
        flags = " | ".join(flag_names[n] for n in names)
        char = comment_text(chr(code))
        lines.append(f"    (0x{code:04X}, {flags}), // {char}")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_autofit_tables.py FREETYPE_SOURCE_DIR")
    autofit = pathlib.Path(sys.argv[1]) / "src" / "autofit"
    scripts = parse_scripts(autofit)
    styles = parse_styles(autofit)
    strings, sets = parse_blues(autofit)
    ranges = parse_ranges(autofit)
    adjustments = parse_adjustments(autofit)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "blues.rs").write_text(emit_blues(strings, sets))
    (OUT / "ranges.rs").write_text(emit_ranges(ranges))
    (OUT / "scripts.rs").write_text(emit_scripts(scripts, styles, hb_scripts(autofit), sets))
    (OUT / "adjustments.rs").write_text(emit_adjustments(adjustments))


if __name__ == "__main__":
    main()
