"""Generate src/shape/unicode_data.rs: scripts, combining classes and canonical
(de)compositions.

Run with the project venv (needs fontTools for Unicode script data):

    .venv/bin/python -I crates/pltrs-font/tools/gen_unicode.py
"""

import pathlib
import unicodedata

from fontTools import unicodedata as fu

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "shape" / "unicode_data.rs"
MAX = 0x110000


def script_ranges():
    """Merged (start, iso_code) runs covering the whole code space."""
    runs = []
    last = None
    for cp in range(MAX):
        code = fu.script(chr(cp))
        if code != last:
            runs.append((cp, code))
            last = code
    return runs


def combining_classes():
    """(start, end, ccc) runs of non-zero canonical combining classes."""
    runs = []
    for cp in range(MAX):
        ccc = unicodedata.combining(chr(cp))
        if not ccc:
            continue
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == ccc:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, ccc])
    return runs


def decompositions():
    """(char, first, second) canonical one-level decompositions (second is 0
    for singletons) and the primary composites among them."""
    decomposed, composed = [], []
    for cp in range(MAX):
        if 0xAC00 <= cp <= 0xD7A3:
            continue  # Hangul syllables are not handled by the default shaper.
        mapping = unicodedata.decomposition(chr(cp))
        if not mapping or mapping.startswith("<"):
            continue
        parts = [int(p, 16) for p in mapping.split()]
        first, second = parts[0], (parts[1] if len(parts) > 1 else 0)
        decomposed.append((cp, first, second))
        if second and unicodedata.normalize("NFC", chr(first) + chr(second)) == chr(cp):
            composed.append((first, second, cp))
    return decomposed, sorted(composed)


def ot_tag(code):
    tags = fu.ot_tags_from_script(code)
    return tags[-1] if tags else None


def wrap(items):
    lines, cur = [], "   "
    for item in items:
        piece = " " + item + ","
        if len(cur) + len(piece) > 100:
            lines.append(cur)
            cur = "   "
        cur += piece
    lines.append(cur)
    return lines


def main():
    runs = script_ranges()
    codes = sorted({code for _, code in runs})
    index = {code: i for i, code in enumerate(codes)}
    out = [
        "//! Unicode tables generated by `tools/gen_unicode.py` from Python's",
        f"//! `unicodedata` (Unicode {unicodedata.unidata_version}) and fontTools' Scripts data.",
        "//! Do not edit by hand.",
        "",
        "/// ISO 15924 code and OpenType script tag (`None` for Common, Inherited",
        "/// and Unknown) of each script, indexed by the values in `SCRIPT_RUNS`.",
        "pub(crate) const SCRIPTS: [(&[u8; 4], Option<&[u8; 4]>); %d] = [" % len(codes),
    ]
    for code in codes:
        tag = ot_tag(code) if code not in ("Zyyy", "Zinh", "Zzzz") else None
        tag_text = "None" if tag is None else 'Some(b"%s")' % tag.ljust(4)
        out.append('    (b"%s", %s),' % (code, tag_text))
    out += [
        "];",
        "",
        "/// Index of the Common script (`Zyyy`) in `SCRIPTS`.",
        "pub(crate) const COMMON: u8 = %d;" % index["Zyyy"],
        "/// Index of the Inherited script (`Zinh`) in `SCRIPTS`.",
        "pub(crate) const INHERITED: u8 = %d;" % index["Zinh"],
        "",
        "/// Script runs: `(first code point, index into SCRIPTS)`; each run extends",
        "/// to the next entry.",
        "pub(crate) static SCRIPT_RUNS: [(u32, u8); %d] = [" % len(runs),
    ]
    out += wrap("(0x%X, %d)" % (cp, index[code]) for cp, code in runs)
    out.append("];")
    ccc = combining_classes()
    out += [
        "",
        "/// Canonical combining classes: `(first, last, class)` for non-zero classes.",
        "pub(crate) static COMBINING_CLASSES: [(u32, u32, u8); %d] = [" % len(ccc),
    ]
    out += wrap("(0x%X, 0x%X, %d)" % tuple(r) for r in ccc)
    decomposed, composed = decompositions()
    out += [
        "];",
        "",
        "/// Canonical one-level decompositions `(char, first, second)`, sorted by",
        "/// char; `second` is 0 for singleton decompositions.",
        "pub(crate) static DECOMPOSITIONS: [(u32, u32, u32); %d] = [" % len(decomposed),
    ]
    out += wrap("(0x%X, 0x%X, 0x%X)" % d for d in decomposed)
    out += [
        "];",
        "",
        "/// Primary composites `(first, second, composed)`, sorted by the pair.",
        "pub(crate) static COMPOSITIONS: [(u32, u32, u32); %d] = [" % len(composed),
    ]
    out += wrap("(0x%X, 0x%X, 0x%X)" % c for c in composed)
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(codes)} scripts, {len(runs)} runs, {len(ccc)} ccc, "
          f"{len(decomposed)} decompositions, {len(composed)} compositions -> {OUT}")


if __name__ == "__main__":
    main()
