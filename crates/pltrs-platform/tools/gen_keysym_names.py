"""Generate the keysym name table of pltrs-platform's keysym module.

XKB keymaps, which Wayland compositors send as text, name every keysym
(`a`, `Return`, `Cyrillic_a`, `XF86AudioMute`). The names and values come
from X.Org's `keysymdef.h` and `XF86keysym.h` (package `x11proto-dev`):

    apt-get download x11proto-dev && dpkg-deb -x x11proto-dev_*.deb x11proto
    python3 -I crates/pltrs-platform/tools/gen_keysym_names.py x11proto/usr/include/X11

Writes crates/pltrs-platform/src/keysym/name_table.rs (committed).
"""

import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "keysym" / "name_table.rs"
PER_LINE = 3
# `#define XK_name 0x1234` and `#define XF86XK_name _EVDEVK(0x0f4)`.
DEFINE = re.compile(r"^#define (XK_|XF86XK_)(\w+)\s+(?:0x([0-9a-fA-F]+)|_EVDEVK\(0x([0-9a-fA-F]+)\))")
EVDEVK_BASE = 0x10081000


def keysyms(include):
    names = {}
    for header in ("keysymdef.h", "XF86keysym.h"):
        for line in (include / header).read_text(encoding="latin-1").splitlines():
            match = DEFINE.match(line)
            if not match:
                continue
            prefix, name, plain, evdev = match.groups()
            value = int(plain, 16) if plain else EVDEVK_BASE + int(evdev, 16)
            names["XF86" + name if prefix == "XF86XK_" else name] = value
    return sorted(names.items(), key=lambda item: item[0].encode())


def literal(value):
    """A hexadecimal literal, digits grouped by four as clippy asks."""
    if value <= 0xFFFF:
        return f"{value:#x}"
    return f"0x{value >> 16:04x}_{value & 0xFFFF:04x}"


def main():
    table = keysyms(pathlib.Path(sys.argv[1]))
    entries = [f'("{name}", {literal(value)})' for name, value in table]
    rows = [
        "    " + ", ".join(entries[i:i + PER_LINE]) + ","
        for i in range(0, len(entries), PER_LINE)
    ]
    OUT.write_text(f"""//! The names of X keysyms, as XKB keymaps write them.
//!
//! Generated by `crates/pltrs-platform/tools/gen_keysym_names.py` from
//! X.Org's `keysymdef.h` and `XF86keysym.h`. Do not edit by hand.

/// `(name, keysym)`, sorted by name (bytewise).
#[rustfmt::skip]
pub(super) static NAMES: [(&str, u32); {len(table)}] = [
{chr(10).join(rows)}
];
""")


if __name__ == "__main__":
    main()
