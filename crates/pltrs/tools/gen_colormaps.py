"""Generate the built-in colormap definitions of pltrs::colors::colormaps.

Run with the reference venv, then format:

    .venv/bin/python -I crates/pltrs/tools/gen_colormaps.py
    rustfmt --edition 2024 crates/pltrs/src/colors/colormaps/{listed_data,builtin_data}.rs

Writes crates/pltrs/src/colors/colormaps/{listed_data,builtin_data}.rs
(committed). The tables are matplotlib's *definitions* from `_cm.py` and
`_cm_listed.py` -- segment anchors, colour lists and the names of the
segment functions -- not sampled lookup tables; pltrs builds the LUTs the
way matplotlib does. Qualitative maps reuse the colour-sequence tables that
`gen_color_tables.py` writes, so their data exists once.
"""

import functools
import pathlib

import matplotlib as mpl
from matplotlib import _cm, _cm_listed

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "colors" / "colormaps"
HEADER = """//! {what}
//!
//! Generated by `crates/pltrs/tools/gen_colormaps.py` from matplotlib's
//! `_cm.py` and `_cm_listed.py`. Do not edit by hand.

#![allow(
    clippy::unreadable_literal,
    clippy::approx_constant,
    reason = "exact floats copied from matplotlib"
)]
"""

# twilight_shifted is defined in _cm_listed.py by rotating twilight by half
# its length and reversing it; pltrs derives it the same way.
DERIVED = {"twilight_shifted": "twilight"}

NAMED_FUNCS = {
    "_flag_red": "FlagRed",
    "_flag_green": "FlagGreen",
    "_flag_blue": "FlagBlue",
    "_prism_red": "PrismRed",
    "_prism_green": "PrismGreen",
    "_prism_blue": "PrismBlue",
    "_gist_heat_red": "GistHeatRed",
    "_gist_heat_green": "GistHeatGreen",
    "_gist_heat_blue": "GistHeatBlue",
    "_gist_yarg": "GistYarg",
}


def num(value):
    return repr(float(value))


def rgb(row):
    r, g, b = row
    return f"[{num(r)}, {num(g)}, {num(b)}]"


def const_name(name):
    return name.upper()


def listed_data():
    rows = [HEADER.format(what="RGB tables of the perceptual colormaps in `_cm_listed.py`.")]
    for name, cmap in _cm_listed.cmaps.items():
        if name in DERIVED:
            continue
        data = getattr(_cm_listed, f"_{name}_data")
        rows.append(f"/// `{name}` ({len(data)} colours).")
        rows.append(f"pub(super) const {const_name(name)}: &[[f64; 3]] = &[")
        rows += [f"    {rgb(row)}," for row in data]
        rows.append("];")
        rows.append("")
    (OUT / "listed_data.rs").write_text("\n".join(rows))


def segment_function(func):
    if isinstance(func, functools.partial):
        if func.func is not _cm._ch_helper:
            raise ValueError(f"unknown partial segment function {func}")
        params = ", ".join(num(a) for a in func.args)
        return f"BuiltinFn::Cubehelix([{params}])"
    for index, candidate in _cm.gfunc.items():
        if func is candidate:
            return f"BuiltinFn::Gnuplot({index})"
    return f"BuiltinFn::{NAMED_FUNCS[func.__name__]}"


def channel(data):
    if callable(data):
        return f"ChannelDef::Func({segment_function(data)})"
    anchors = ", ".join(f"[{num(x)}, {num(y0)}, {num(y1)}]" for x, y0, y1 in data)
    return f"ChannelDef::Anchors(&[{anchors}])"


def definition(name, spec):
    if "red" in spec:
        if set(spec) != {"red", "green", "blue"}:
            raise ValueError(f"{name}: unexpected channels {sorted(spec)}")
        channels = ", ".join(channel(spec[key]) for key in ("red", "green", "blue"))
        return f"Builtin::Segmented([{channels}])"
    if "listed" in spec:
        expected = [tuple(map(float, c)) for c in mpl.color_sequences[name]]
        if [tuple(map(float, c)) for c in spec["listed"]] != expected:
            raise ValueError(f"{name}: listed data differs from its colour sequence")
        return f'Builtin::Sequence("{name}")'
    if isinstance(spec[0][1], tuple):
        stops = ", ".join(f"({num(value)}, {rgb(color)})" for value, color in spec)
        return f"Builtin::FromStops(&[{stops}])"
    colors = ", ".join(rgb(color) for color in spec)
    return f"Builtin::FromList(&[{colors}])"


def builtin_data():
    rows = [HEADER.format(what="Every built-in base colormap, in matplotlib's registry order."),
            "use super::builtin::{Builtin, BuiltinFn, ChannelDef};",
            "use super::listed_data;",
            "",
            "/// `(name, definition)` for each base colormap (aliases and `_r`",
            "/// reversals are derived from these).",
            "pub(super) const BUILTINS: &[(&str, Builtin)] = &["]
    for name in _cm_listed.cmaps:
        if name in DERIVED:
            rows.append(f'    ("{name}", Builtin::Shifted(listed_data::{const_name(DERIVED[name])})),')
        else:
            rows.append(f'    ("{name}", Builtin::Listed(listed_data::{const_name(name)})),')
    for name, spec in _cm.datad.items():
        rows.append(f'    ("{name}", {definition(name, spec)}),')
    rows.append("];")
    (OUT / "builtin_data.rs").write_text("\n".join(rows) + "\n")


def check_derivation():
    twilight = _cm_listed._twilight_data
    half = len(twilight) // 2
    shifted = twilight[half:] + twilight[:half]
    shifted.reverse()
    if shifted != _cm_listed._twilight_shifted_data:
        raise ValueError("twilight_shifted is no longer derived from twilight")


if __name__ == "__main__":
    check_derivation()
    listed_data()
    builtin_data()
    print("wrote", OUT / "listed_data.rs", OUT / "builtin_data.rs")
