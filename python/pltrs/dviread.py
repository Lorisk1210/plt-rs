"""
A module for reading dvi files output by TeX, and the files of the TeX
installation they refer to (matplotlib's ``dviread``).

pltrs (Rust) reads them itself (pltrs-text's usetex), the DVI files of
LaTeX, XeTeX and LuaTeX alike, and finds TeX's files with kpathsea, as
matplotlib does.

Interface::

  with Dvi(filename, 72) as dvi:
      # iterate over pages:
      for page in dvi:
          w, h, d = page.width, page.height, page.descent
          for x, y, font, glyph, width in page.text:
              fontname = font.texname
              pointsize = font.size
              ...
          for x, y, height, width in page.boxes:
              ...
"""

from collections import namedtuple
import dataclasses
from functools import cached_property, lru_cache
import logging
from numbers import Integral
import os
from pathlib import Path

from . import _api
from ._native import dviread as _dviread

_log = logging.getLogger(__name__)

# The marks on a page consist of text and boxes. A page also has dimensions.
Page = namedtuple('Page', 'text boxes height width descent')
Box = namedtuple('Box', 'x y height width')


# Also a namedtuple, for backcompat.
class Text(namedtuple('Text', 'x y font glyph width')):
    """
    A glyph in the dvi file.

    In order to render the glyph, load the glyph at index ``text.index``
    from the font at ``text.font.resolve_path()`` with size ``text.font.size``,
    warped with ``text.font.effects``, then draw it at position
    ``(text.x, text.y)``.

    ``text.glyph`` is the glyph number actually stored in the dvi file (whose
    interpretation depends on the font).  ``text.width`` is the glyph width in
    dvi units.
    """

    @property
    def index(self):
        """
        The FreeType index of this glyph (that can be passed to FT_Load_Glyph).
        """
        return self.font._index_dvi_to_freetype(self.glyph)

    font_path = property(lambda self: self.font.resolve_path())
    font_size = property(lambda self: self.font.size)
    font_effects = property(lambda self: self.font.effects)

    @property  # To be deprecated together with font_path, font_size, font_effects.
    def glyph_name_or_index(self):
        """
        The glyph name, the native charmap glyph index, or the raw glyph index.

        If the font is a TrueType file (which can currently only happen for
        DVI files generated by xetex or luatex), then this number is the raw
        index of the glyph, which can be passed to FT_Load_Glyph/load_glyph.

        Otherwise, the font is a PostScript font.  For such fonts, if
        :file:`pdftex.map` specifies an encoding for this glyph's font,
        that is a mapping of glyph indices to Adobe glyph names; which
        is used by this property to convert dvi numbers to glyph names.
        Callers can then convert glyph names to glyph indices (with
        FT_Get_Name_Index/get_name_index), and load the glyph using
        FT_Load_Glyph/load_glyph.

        If :file:`pdftex.map` specifies no encoding for a PostScript font,
        this number is an index to the font's "native" charmap; glyphs should
        directly load using FT_Load_Char/load_char after selecting the native
        charmap.
        """
        entry = PsfontsMap(find_tex_file("pdftex.map"))[self.font.texname]
        return (_parse_enc(entry.encoding)[self.glyph]
                if entry.encoding is not None else self.glyph)

    def _as_unicode_or_name(self):
        if self.font.subfont:
            raise NotImplementedError("Indexing TTC fonts is not supported yet")
        path = self.font.resolve_path()
        if path.name.lower().endswith("pk"):
            # PK fonts have no encoding information; report glyphs as ASCII but
            # with a "?" to indicate that this is just a guess.
            return (f"{chr(self.glyph)}?" if chr(self.glyph).isprintable() else
                    f"pk{self.glyph:#02x}")
        return _dviread.unicode_or_name(self.font._native, self.glyph)


class Dvi:
    """
    A reader for a dvi ("device-independent") file, as produced by TeX.

    The current implementation can only iterate through pages in order,
    and does not even attempt to verify the postamble.

    This class can be used as a context manager to close the underlying
    file upon exit. Pages can be read via iteration. Here is an overly
    simple way to extract text without trying to detect whitespace::

        >>> with matplotlib.dviread.Dvi('input.dvi', 72) as dvi:
        ...     for page in dvi:
        ...         print(''.join(chr(t.glyph) for t in page.text))
    """

    def __init__(self, filename, dpi):
        """
        Read the data from the file named *filename* and convert
        TeX's internal units to units of *dpi* per inch.
        *dpi* only sets the units and does not limit the resolution.
        Use None to return TeX's internal units.
        """
        _log.debug('Dvi: %s', filename)
        self.file = open(filename, 'rb')
        self.dpi = dpi

    def __enter__(self):
        """Context manager enter method, does nothing."""
        return self

    def __exit__(self, etype, evalue, etrace):
        """
        Context manager exit method, closes the underlying file if it is open.
        """
        self.close()

    def __iter__(self):
        """
        Iterate through the pages of the file.

        Yields
        ------
        Page
            Details of all the text and box objects on the page.
            The Page tuple contains lists of Text and Box tuples and
            the page dimensions, and the Text and Box tuples contain
            coordinates transformed into a standard Cartesian
            coordinate system at the dpi value given when initializing.
            The coordinates are floating point numbers, but otherwise
            precision is not lost and coordinate values are not clipped to
            integers.
        """
        fonts, pages = _dviread.read_pages(self.file.read(), self.dpi)
        self.close()
        fonts = [DviFont._from_native(font) for font in fonts]
        for text, boxes, height, width, descent in pages:
            yield Page(
                text=[Text(x, y, fonts[font], glyph, w)
                      for x, y, font, glyph, w in text],
                boxes=[Box(*box) for box in boxes],
                height=height, width=width, descent=descent)

    def close(self):
        """Close the underlying file if it is open."""
        if not self.file.closed:
            self.file.close()


def _mul1220(num1, num2):
    """Multiply two numbers in 20.12 fixed point format."""
    # Separated into a function because >> has surprising precedence
    return (num1*num2) >> 20


def _native_scale(scale):
    """
    The 12.20 fixed-point scale pltrs (Rust) makes a font of *scale* with:
    *scale* itself, an integer as DVI files give it. matplotlib's font
    keeps any other value as it is, computing its size and its widths with
    it (`DviFont`), so pltrs (Rust) only holds the integral part of a
    number, and 0 for anything else.
    """
    try:
        return int(scale)
    except (TypeError, ValueError, OverflowError):
        return 0


class DviFont:
    """
    Encapsulation of a font that a DVI file can refer to.

    This class holds a font's texname and size, supports comparison,
    and knows the widths of glyphs in the same units as the AFM file.
    There are also internal attributes (for use by dviread.py) that
    are *not* used for comparison.

    The size is in Adobe points (converted from TeX points).

    Parameters
    ----------
    scale : float
        Factor by which the font is scaled from its natural size.
    metrics : Tfm | TtfMetrics
        TeX font metrics for this font
    texname : bytes
       Name of the font as used internally in the DVI file, as an ASCII
       bytestring.  This is usually very different from any external font
       names; `PsfontsMap` can be used to find the external name of the font.
    vf : Vf
       A TeX "virtual font" file, or None if this font is not virtual.

    Attributes
    ----------
    texname : bytes
    fname : str
       Compatibility shim so that DviFont can be used with
       ``_backend_pdf_ps.CharacterTracker``; not a real filename.
    size : float
       Size of the font in Adobe points, converted from the slightly
       smaller TeX points.
    """
    # pltrs (Rust) makes the fonts of the DVI files it reads: their metrics
    # come from TeX font metrics, or from the OpenType and TrueType files of
    # the native fonts of XeTeX and LuaTeX.

    def __init__(self, scale, metrics, texname, vf):
        _api.check_isinstance(bytes, texname=texname)
        self._set_native(_dviread.font_new(
            _native_scale(scale), metrics._native, texname,
            None if vf is None else vf._native))
        self._scale = scale
        self._metrics = metrics
        self._vf = vf

    @classmethod
    def _from_native(cls, native, scale=None):
        """The font of the native DVI font *native*, of *scale* as the
        program gave it (one that is no integer, see `_native_scale`)."""
        self = cls.__new__(cls)
        self._set_native(native)
        if scale is not None:
            self._scale = scale
        return self

    def _set_native(self, native):
        """Make the font that of the native DVI font *native*."""
        self._native = native
        self.texname, self._scale, _ = _dviread.font_name_and_size(native)
        self._path = None

    @cached_property
    def _metrics(self):
        """The metrics of the glyphs: TeX font metrics, or those of the
        font file of a native font."""
        tfm, face = _dviread.font_metrics(self._native)
        return Tfm._from_native(tfm) if tfm is not None else TtfMetrics._from_native(face)

    @classmethod
    def from_luatex(cls, scale, texname):
        # The name is checked first, as matplotlib's reads it before the
        # scale.
        _path_b, sep, rest = texname[1:].rpartition(b"]")
        if not (texname.startswith(b"[") and sep and rest[:1] in [b"", b":"]):
            raise ValueError(f"Invalid modern font name: {texname}")
        return cls._from_native(_dviread.font_from_luatex(scale, texname))

    @classmethod
    def from_xetex(cls, scale, texname, subfont, effects):
        return cls._from_native(_dviread.font_from_xetex(
            _native_scale(scale), texname, subfont,
            tuple(effects.get(key) for key in
                  ("rgba", "extend", "slant", "embolden"))), scale)

    size = property(lambda self: self._scale * (72.0 / (72.27 * 2**16)))

    # matplotlib 3.11's deprecated property, as it is: it reads the TFM
    # file fonts no longer keep (``_tfm``), so it raises AttributeError.
    widths = _api.deprecated("3.11")(property(lambda self: [
        (1000 * self._tfm.width.get(char, 0)) >> 20
        for char in range(max(self._tfm.width, default=-1) + 1)]))

    @property
    def fname(self):
        """A fake filename"""
        return self.texname.decode('latin-1')

    @property
    def face_index(self):  # For compatibility with FT2Font.
        return 0

    def _get_fontmap(self, string):
        """Get the mapping from characters to the font that includes them.

        Each value maps to self; there is no fallback mechanism for DviFont.
        """
        return {char: self for char in string}

    def __eq__(self, other):
        return (type(self) is type(other)
                and self.texname == other.texname and self.size == other.size)

    def __ne__(self, other):
        return not self.__eq__(other)

    def __repr__(self):
        return f"<{type(self).__name__}: {self.texname}>"

    def _width_of(self, char):
        """Width of char in dvi units."""
        if not isinstance(self._scale, Integral):
            # matplotlib's fixed-point product with a scale that is no
            # integer fails on its shift.
            metrics = self._metrics.get_metrics(char)
            return 0 if metrics is None else _mul1220(metrics.tex_width, self._scale)
        return _dviread.font_width_of(self._native, char)

    def _height_depth_of(self, char):
        """Height and depth of char in dvi units."""
        if not isinstance(self._scale, Integral):
            metrics = self._metrics.get_metrics(char)
            return [0, 0] if metrics is None else [
                _mul1220(metrics.tex_height, self._scale),
                _mul1220(metrics.tex_depth, self._scale)]
        return list(_dviread.font_height_depth_of(self._native, char))

    def resolve_path(self):
        if self._path is None:
            self._path = Path(_dviread.font_path(self._native))
        return self._path

    @cached_property
    def subfont(self):
        return _dviread.font_subfont(self._native)

    @cached_property
    def effects(self):
        return _dviread.font_effects(self._native)

    def _index_dvi_to_freetype(self, idx):
        """Convert dvi glyph indices to FreeType ones."""
        return _dviread.font_glyph_index(self._native, idx)


class Vf(Dvi):
    r"""
    A virtual font (\*.vf file) containing subroutines for dvi files.

    Parameters
    ----------
    filename : str or path-like

    Notes
    -----
    The virtual font format is a derivative of dvi:
    http://mirrors.ctan.org/info/knuth/virtual-fonts
    This class reuses some of the machinery of `Dvi`
    but replaces the `!_read` loop and dispatch mechanism.

    Examples
    --------
    ::

        vf = Vf(filename)
        glyph = vf[code]
        glyph.text, glyph.boxes, glyph.width
    """

    def __init__(self, filename):
        super().__init__(filename, 0)
        try:
            self._native = _dviread.vf(self.file.read())
        finally:
            self.close()

    def __getitem__(self, code):
        packet = _dviread.vf_packet(self._native, code)
        if packet is None:
            raise KeyError(code)
        text, boxes, width = packet
        return Page(
            text=[Text(x, y, DviFont._from_native(font), glyph, w)
                  for x, y, font, glyph, w in text],
            boxes=[Box(*box) for box in boxes],
            width=width, height=None, descent=None)


@dataclasses.dataclass(frozen=True, kw_only=True)
class TexMetrics:
    """
    Metrics of a glyph, with TeX semantics.

    TeX metrics have different semantics from FreeType metrics: tex_width
    corresponds to FreeType's ``advance`` (i.e., including whitespace padding);
    tex_height to ``bearingY`` (how much the glyph extends over the baseline);
    tex_depth to ``height - bearingY`` (how much the glyph extends under the
    baseline, as a positive number).
    """
    tex_width: int
    tex_height: int
    tex_depth: int


def _tex_metrics(fields):
    """The `TexMetrics` of native ``(width, height, depth)`` fields."""
    if fields is None:
        return None
    width, height, depth = fields
    return TexMetrics(tex_width=width, tex_height=height, tex_depth=depth)


class Tfm:
    """
    A TeX Font Metric file.

    This implementation covers only the bare minimum needed by the Dvi class.

    Parameters
    ----------
    filename : str or path-like

    Attributes
    ----------
    checksum : int
       Used for verifying against the dvi file.
    design_size : int
       Design size of the font (in 12.20 TeX points); unused because it is
       overridden by the scale factor specified in the dvi file.
    """

    def __init__(self, filename):
        _log.debug('opening tfm file %s', filename)
        with open(filename, 'rb') as file:
            self._set_native(_dviread.tfm(file.read()))

    @classmethod
    def _from_native(cls, native):
        """The metrics of the native TFM file *native*."""
        self = cls.__new__(cls)
        self._set_native(native)
        return self

    def _set_native(self, native):
        """Make the metrics those of the native TFM file *native*."""
        self._native = native
        self.checksum, self.design_size = _dviread.tfm_header(native)

    def get_metrics(self, idx):
        """Return a glyph's TexMetrics, or None if unavailable."""
        return _tex_metrics(_dviread.tfm_metrics(self._native, idx))

    @property
    def _glyph_metrics(self):
        """The metrics of every character, by code."""
        return {code: self.get_metrics(code)
                for code in _dviread.tfm_codes(self._native)}

    # matplotlib 3.11's deprecated properties, as they are: they iterate
    # over the codes of ``_glyph_metrics`` as if over its items, so they
    # raise TypeError.
    width = _api.deprecated("3.11", alternative="get_metrics")(
        property(lambda self: {c: m.tex_width for c, m in self._glyph_metrics}))
    height = _api.deprecated("3.11", alternative="get_metrics")(
        property(lambda self: {c: m.tex_height for c, m in self._glyph_metrics}))
    depth = _api.deprecated("3.11", alternative="get_metrics")(
        property(lambda self: {c: m.tex_depth for c, m in self._glyph_metrics}))


class TtfMetrics:
    def __init__(self, filename):
        self._native = _dviread.ttf_metrics(os.fspath(filename))

    @classmethod
    def _from_native(cls, native):
        """The metrics of the native font file *native*."""
        self = cls.__new__(cls)
        self._native = native
        return self

    def get_metrics(self, idx):
        return _tex_metrics(_dviread.ttf_metrics_get(self._native, idx))


@lru_cache
def find_tex_file(filename):
    """
    Find a file in the texmf tree using kpathsea_.

    The kpathsea library, provided by most existing TeX distributions, both
    on Unix-like systems and on Windows (MikTeX), is invoked via a long-lived
    luatex process if luatex is installed, or via kpsewhich otherwise.

    .. _kpathsea: https://www.tug.org/kpathsea/

    Parameters
    ----------
    filename : str or path-like

    Raises
    ------
    FileNotFoundError
        If the file is not found.
    """
    # we expect these to always be ascii encoded, but use utf-8
    # out of caution
    if isinstance(filename, bytes):
        filename = filename.decode('utf-8', errors='replace')
    return _dviread.find_tex_file(os.fspath(filename))


PsFont = namedtuple('PsFont', 'texname psname effects encoding filename')


def _lookup_replaced(texname):
    """Look TeX font *texname* up with the program's replacement of
    `PsfontsMap.__getitem__`, as pltrs (Rust) does while it is in force."""
    return PsfontsMap(find_tex_file("pdftex.map"))[texname]


class PsfontsMap:
    """
    A psfonts.map formatted file, mapping TeX fonts to PS fonts.

    Parameters
    ----------
    filename : str or path-like

    Notes
    -----
    For historical reasons, TeX knows many Type-1 fonts by different
    names than the outside world. (For one thing, the names have to
    fit in eight characters.) Also, TeX's native fonts are not Type-1
    but Metafont, which is nontrivial to convert to PostScript except
    as a bitmap. While high-quality conversions to Type-1 format exist
    and are shipped with modern TeX distributions, we need to know
    which Type-1 fonts are the counterparts of which native fonts. For
    these reasons a mapping is needed from internal font names to font
    file names.

    A texmf tree typically includes mapping files called e.g.
    :file:`psfonts.map`, :file:`pdftex.map`, or :file:`dvipdfm.map`.
    The file :file:`psfonts.map` is used by :program:`dvips`,
    :file:`pdftex.map` by :program:`pdfTeX`, and :file:`dvipdfm.map`
    by :program:`dvipdfm`. :file:`psfonts.map` might avoid embedding
    the 35 PostScript fonts (i.e., have no filename for them, as in
    the Times-Bold example above), while the pdf-related files perhaps
    only avoid the "Base 14" pdf fonts. But the user may have
    configured these files differently.

    Examples
    --------
    >>> map = PsfontsMap(find_tex_file('pdftex.map'))
    >>> entry = map[b'ptmbo8r']
    >>> entry.texname
    b'ptmbo8r'
    >>> entry.psname
    b'Times-Bold'
    >>> entry.encoding
    '/usr/local/texlive/2008/texmf-dist/fonts/enc/dvips/base/8r.enc'
    >>> entry.effects
    {'slant': 0.16700000000000001}
    >>> entry.filename
    """
    __slots__ = ('_filename', '_native')

    # Create a filename -> PsfontsMap cache, so that calling
    # `PsfontsMap(filename)` with the same filename a second time immediately
    # returns the same object.
    @lru_cache
    def __new__(cls, filename):
        self = object.__new__(cls)
        self._filename = os.fsdecode(filename)
        # The lines are only parsed when a font they define is asked for:
        # some TeX distributions have enormous pdftex.map files.
        with open(filename, 'rb') as file:
            self._native = _dviread.psfonts_map(file.read(), self._filename)
        return self

    def __getitem__(self, texname):
        assert isinstance(texname, bytes)
        return PsFont(*_dviread.psfonts_map_get(
            self._native, texname, find_tex_file))


# usetex looks fonts up through the program's replacement of
# ``PsfontsMap.__getitem__`` while there is one, as matplotlib's does.
_dviread.set_font_lookup(_lookup_replaced,
                         (PsfontsMap, "__getitem__", PsfontsMap.__getitem__))


def _parse_enc(path):
    r"""
    Parse a \*.enc file referenced from a psfonts.map style file.

    The format supported by this function is a tiny subset of PostScript.

    Parameters
    ----------
    path : `os.PathLike`

    Returns
    -------
    list
        The nth list item is the PostScript glyph name of the nth glyph.
    """
    return _dviread.parse_enc(Path(path).read_bytes())


