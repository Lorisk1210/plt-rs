"""
Streamline plotting for 2D vector fields (matplotlib's ``streamplot``).

The checks of the grid and the arguments are matplotlib's (from matplotlib
3.11.2, under the Matplotlib License); pltrs (Rust) traces the streamlines
and draws them with their arrows, but for arguments it does not take as
they are, whose streamlines matplotlib's code makes.
"""

import math
import operator
from numbers import Integral, Real

import numpy as np

from . import (_api, _handles, _lazy_imports, _live_transforms, _values, cbook,
               colors as mcolors, collections as mcollections, patches)
from ._fancy_styles import _style_object
from ._native import patches as _patches, plotting as _plotting
from ._patch_styles import ArrowStyle, _native_spec
from ._stream_grid import (  # noqa: F401 - matplotlib's names of the module
    DomainMap, Grid, InvalidIndexError, OutOfBounds, StreamMask, TerminateTrajectory, interpgrid)

_streamplot_reference = _lazy_imports.module(globals(), "._streamplot_reference")


__all__ = ['streamplot']

cbook._set_module(__name__, DomainMap, Grid, InvalidIndexError, OutOfBounds,
                  StreamMask, TerminateTrajectory, interpgrid)


def _grid_axis(values, name):
    """The 1D coordinates of the grid along *name* (``'x'`` or ``'y'``) that
    `Grid` checked: *values* itself, or the row (x) or column (y) of a 2D
    mesh."""
    if np.ndim(values) == 1:
        return np.asarray(values, dtype=float)
    mesh = values if name == 'x' else np.transpose(values)
    return np.asarray(mesh[0], dtype=float)


def _filled(values):
    """*values* as a float array, NaN where masked or invalid."""
    return np.ma.filled(np.ma.masked_invalid(np.ma.asarray(values, dtype=float)),
                        np.nan)


def _taken_natively(linewidth, arrowsize, arrowstyle, minlength, maxlength, zorder,
                    num_arrows):
    """Whether pltrs (Rust) takes the arguments as they are: numbers where
    matplotlib computes with numbers (a finite arrow size, a minimum length
    that is not negative, a whole number of arrows), a style given by name
    or as a style; matplotlib's own code makes the streamlines of any
    others (`._streamplot_reference`)."""
    return ((linewidth is None or isinstance(linewidth, (Real, np.ndarray)))
            and isinstance(arrowsize, Real) and math.isfinite(arrowsize)
            and (isinstance(arrowstyle, str) or callable(arrowstyle))
            and isinstance(minlength, Real) and not minlength < 0
            and isinstance(maxlength, Real)
            and (zorder is None or isinstance(zorder, Real))
            and isinstance(num_arrows, Integral))


def streamplot(axes, x, y, u, v, density=1, linewidth=None, color=None,
               cmap=None, norm=None, arrowsize=1, arrowstyle='-|>',
               minlength=0.1, transform=None, zorder=None, start_points=None,
               maxlength=4.0, integration_direction='both',
               broken_streamlines=True, *, integration_max_step_scale=1.0,
               integration_max_error_scale=1.0, num_arrows=1):
    """
    Draw streamlines of a vector flow.

    Parameters
    ----------
    x, y : 1D/2D arrays
        Evenly spaced strictly increasing arrays to make a grid.  If 2D, all
        rows of *x* must be equal and all columns of *y* must be equal; i.e.,
        they must be as if generated by ``np.meshgrid(x_1d, y_1d)``.
    u, v : 2D arrays
        *x* and *y*-velocities. The number of rows and columns must match
        the length of *y* and *x*, respectively.
    density : float or (float, float)
        Controls the closeness of streamlines. When ``density = 1``, the domain
        is divided into a 30x30 grid. *density* linearly scales this grid.
        Each cell in the grid can have, at most, one traversing streamline.
        For different densities in each direction, use a tuple
        (density_x, density_y).
    linewidth : float or 2D array
        The width of the streamlines. With a 2D array the line width can be
        varied across the grid. The array must have the same shape as *u*
        and *v*.
    color : :mpltype:`color` or 2D array
        The streamline color. If given an array, its values are converted to
        colors using *cmap* and *norm*.  The array must have the same shape
        as *u* and *v*.
    cmap, norm
        Data normalization and colormapping parameters for *color*; only used
        if *color* is an array of floats. See `~.Axes.imshow` for a detailed
        description.
    arrowsize : float
        Scaling factor for the arrow size.
    arrowstyle : str
        Arrow style specification.
        See `~matplotlib.patches.FancyArrowPatch`.
    minlength : float
        Minimum length of streamline in axes coordinates.
    start_points : (N, 2) array
        Coordinates of starting points for the streamlines in data coordinates
        (the same coordinates as the *x* and *y* arrays).
    zorder : float
        The zorder of the streamlines and arrows.
        Artists with lower zorder values are drawn first.
    maxlength : float
        Maximum length of streamline in axes coordinates.
    integration_direction : {'forward', 'backward', 'both'}, default: 'both'
        Integrate the streamline in forward, backward or both directions.
    data : indexable object, optional
        DATA_PARAMETER_PLACEHOLDER
    broken_streamlines : boolean, default: True
        If False, forces streamlines to continue until they
        leave the plot domain.  If True, they may be terminated if they
        come too close to another streamline.
    integration_max_step_scale : float, default: 1.0
        Multiplier on the maximum allowable step in the streamline integration routine.
        A value between zero and one results in a max integration step smaller than
        the default max step, resulting in more accurate streamlines at the cost
        of greater computation time; a value greater than one does the converse. Must be
        greater than zero.

        .. versionadded:: 3.11

    integration_max_error_scale : float, default: 1.0
        Multiplier on the maximum allowable error in the streamline integration routine.
        A value between zero and one results in a tighter max integration error than
        the default max error, resulting in more accurate streamlines at the cost
        of greater computation time; a value greater than one does the converse. Must be
        greater than zero.

        .. versionadded:: 3.11

    num_arrows : int
        Number of arrows per streamline. The arrows are spaced equally along the steps
        each streamline takes. Note that this can be different to being spaced equally
        along the distance of the streamline.


    Returns
    -------
    StreamplotSet
        Container object with attributes

        - ``lines``: `.LineCollection` of streamlines

        - ``arrows``: `.PatchCollection` containing `.FancyArrowPatch`
          objects representing the arrows half-way along streamlines.

        This container will probably change in the future to allow changes
        to the colormap, alpha, etc. for both lines and arrows, but these
        changes should be backward compatible.
    """
    if not _taken_natively(linewidth, arrowsize, arrowstyle, minlength, maxlength,
                           zorder, num_arrows):
        return StreamplotSet(*_streamplot_reference.streamplot(
            axes, x, y, u, v, density, linewidth, color, cmap, norm, arrowsize,
            arrowstyle, minlength, transform, zorder, start_points, maxlength,
            integration_direction, broken_streamlines,
            integration_max_step_scale=integration_max_step_scale,
            integration_max_error_scale=integration_max_error_scale,
            num_arrows=num_arrows))
    # matplotlib's grid and mask, which check the coordinates and density.
    grid = Grid(x, y)
    DomainMap(grid, StreamMask(density))
    gx = _grid_axis(x, 'x')
    gy = _grid_axis(y, 'y')
    for name, scale in (("integration_max_step_scale", integration_max_step_scale),
                        ("integration_max_error_scale", integration_max_error_scale)):
        if scale <= 0.0:
            raise ValueError(f"The value of {name} must be > 0, got {scale}")
    if num_arrows < 0:
        raise ValueError(f"The value of num_arrows must be >= 0, got {num_arrows=}")
    if transform is None:
        axes.transData  # noqa: B018  (matplotlib's default transform)
    if color is None:
        # Taken from the cycle before the other arguments are checked, as
        # matplotlib takes it.
        color = axes._get_lines.get_next_color()
    # matplotlib computes its arrows' mutation scale and halves the length
    # to integrate each way with here (pltrs (Rust) does so as it traces),
    # failing for values that are no numbers.
    10 * arrowsize  # noqa: B018
    _api.check_in_list(['both', 'forward', 'backward'],
                       integration_direction=integration_direction)
    if integration_direction == 'both':
        operator.itruediv(maxlength, 2.)  # noqa: B018
    shape = grid.shape

    made = mapped = single = None
    if isinstance(color, np.ndarray):
        if color.shape != shape:
            raise ValueError("If 'color' is given, it must match the shape of "
                             "the (x, y) grid")
        from .axes._plotting.scatter import _mapping
        made, mapping = _mapping(cmap, norm, None, None)
        mapped = (_filled(color), mapping)
    elif color is not None:
        single = tuple(map(float, mcolors.to_rgba(color)))

    uniform = varying = None
    if isinstance(linewidth, np.ndarray):
        if linewidth.shape != shape:
            raise ValueError("If 'linewidth' is given, it must match the "
                             "shape of the (x, y) grid")
        varying = np.asarray(linewidth, dtype=float)
    elif linewidth is not None:
        uniform = float(linewidth)

    if u.shape != shape or v.shape != shape:
        raise ValueError("'u' and 'v' must match the shape of the (x, y) grid")

    density = np.broadcast_to(np.asarray(density, dtype=float), (2,))
    if start_points is not None:
        start_points = np.asanyarray(start_points, dtype=float)
        # The columns matplotlib shifts to the grid's origin.
        start_points = np.column_stack([start_points[:, 0], start_points[:, 1]])
    arrowstyle = _native_spec(_style_object(arrowstyle, ArrowStyle), ArrowStyle)
    lines, arrows = _plotting.streamplot(
        axes._native, (gx, gy), (_filled(u), _filled(v)), (single, mapped),
        (uniform, varying),
        ((float(density[0]), float(density[1])), float(minlength),
         float(maxlength), start_points, integration_direction,
         bool(broken_streamlines),
         (float(integration_max_step_scale), float(integration_max_error_scale))),
        (float(arrowsize), arrowstyle, int(num_arrows)),
        (None if zorder is None else float(zorder),
         _live_transforms.given_to_native(transform, axes)))
    figure = axes.figure
    lines = _handles.wrap(lines, mcollections.LineCollection, figure)
    lines._attach_native_mapping(colorizer=made)
    arrows = _handles.wrap_all(arrows, patches.FancyArrowPatch, figure)
    if single is not None:
        for arrow in arrows:
            # matplotlib's ``FancyArrowPatch(color=...)``: the colour given,
            # or the one taken from the cycle, as the cycle holds it.
            for side in ("facecolor", "edgecolor"):
                _values.remember(arrow, side, color)
    # matplotlib's collection of the arrows, which no axes holds ("Adding
    # the collection itself is broken; see #2341."): the arrows are the
    # axes' patches, each added by ``add_patch``, which makes its path.
    collection = mcollections.PatchCollection(arrows)
    for arrow in arrows:
        _patches.warn_making_path(arrow._native)
    # matplotlib autoscales the view at once (``autoscale_view``).
    axes._unstale_viewLim()
    return StreamplotSet(lines, collection)


class StreamplotSet:
    def __init__(self, lines, arrows):
        self.lines = lines
        self.arrows = arrows


