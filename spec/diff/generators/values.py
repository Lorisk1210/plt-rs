"""The values the ``api`` generator gives parameters.

``VALUES`` maps a parameter to the values a program gives it, the
representative first, then the edge values (empty, NaN, inf, a wrong
type, out of range); keys are ``Owner.name.param``, ``name.param`` or
``param``, the most specific found first. ``ARGS`` maps a callable
(``api_index`` key) to the argument lists of its calls, written out,
where a value per parameter does not make a call (the parameters depend
on each other) or the callable needs more than one.

The values name what ``subjects.PRELUDE`` and the subjects define:
``fig``, ``ax``, ``obj``, ``renderer``, ``gc``, ``square`` (a path),
``bbox``, ``affine``, ``prop``, the events ``mouse``, ``release``,
``motion`` and ``keypress``, ``days`` (dates), ``rgba`` and ``pixels``
(images).
"""

