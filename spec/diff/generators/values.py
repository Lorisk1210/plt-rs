def args_for(callable_: Any) -> list[str] | None:
    """The argument lists written out for ``callable_``: its own, or, for
    a pyplot function wrapping an ``Axes`` method, the method's."""
    explicit = ARGS.get(callable_.key)
    if explicit is None and callable_.module == "matplotlib.pyplot":
        for owner in ("Axes", "_AxesBase"):
            explicit = ARGS.get(f"matplotlib.axes:{owner}.{callable_.name}")
            if explicit is not None:
                break
    return explicit

