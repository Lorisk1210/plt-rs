# fig.clear / clf(keep_observers) / ax.clear / cla on figures with callbacks, subfigures, suptitles and legends: what remains.
import matplotlib
matplotlib.use("agg")
import matplotlib.pyplot as plt

fig, axs = plt.subplots(1, 2)
fig.suptitle("sup")
fig.legend(["x"])
fig.text(0.5, 0.5, "free text")
axs[0].plot([0, 1])
axs[0].set_title("left")
axs[0].legend(["l"])
seen = []
cid = fig.canvas.mpl_connect("draw_event", lambda e: seen.append("draw"))
axs[1].callbacks.connect("xlim_changed", lambda a: seen.append("xlim"))
axs[1].set_xlim(0, 2)
print(seen, len(fig.texts), len(fig.legends), fig._suptitle is not None)
axs[0].clear()
print(len(axs[0].lines), axs[0].get_title(), axs[0].get_legend())
axs[1].cla()
axs[1].set_xlim(0, 3)
print(seen)
fig.clf(keep_observers=True)
print(len(fig.axes), len(fig.texts), len(fig.legends), fig._suptitle)
fig.canvas.draw()
print(seen[-1:])
fig.clear()
fig.canvas.draw()
print(seen[-1:], len(fig.canvas.callbacks.callbacks.get("draw_event", {})))
sfig = plt.figure()
subs = sfig.subfigures(1, 2)
subs[0].add_subplot().plot([1])
subs[0].suptitle("in sub")
subs[1].add_subplot()
print(len(sfig.subfigs), len(sfig.axes), len(subs[0].axes))
subs[0].clear()
print(len(subs[0].axes), subs[0]._suptitle, len(sfig.axes))
sfig.clear()
print(len(sfig.subfigs), len(sfig.axes))
plt.close("all")
