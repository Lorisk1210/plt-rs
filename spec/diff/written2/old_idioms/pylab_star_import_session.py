# An old pylab-style session: from pylab import *, numpy names through pylab, figure/plot/hold-free overplotting and savefig.
import matplotlib
matplotlib.use("agg")
from pylab import *

x = linspace(0, 2 * pi, 50)
figure(figsize=(4, 3))
plot(x, sin(x), "r-", x, cos(x), "b--", x, sin(2 * x), "g:")
title("pylab")
xlabel("x")
grid(True)
axis([0, 2 * pi, -1.5, 1.5])
legend(("sin", "cos", "sin2"), loc="upper right")
savefig("pylab_session.png")
ax = gca()
print(len(ax.lines), [l.get_color() for l in ax.lines], [l.get_linestyle() for l in ax.lines])
print(axis(), type(ax).__name__)
print(round(float(mean(sin(x))), 6), round(float(std(cos(x))), 6), type(rand).__name__ if "rand" in dir() else None)
clf()
subplot(211)
bar(arange(4), [3, 1, 4, 1])
subplot(212)
hist(sin(x), bins=5)
savefig("pylab_bars.png")
print(len(gcf().axes), [len(a.patches) for a in gcf().axes])
print(isinstance(gcf(), matplotlib.figure.Figure), "plt" in dir(), "np" in dir())
close("all")
print(get_fignums())
figure()
imshow(eye(3))
colorbar()
print(len(gcf().axes), gci() is not None)
