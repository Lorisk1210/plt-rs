# Keep the renderer from the first draw, measure artists with it after changing the text, and compare with fresh draws.
import matplotlib
matplotlib.use("agg")
import matplotlib.pyplot as plt

fig, ax = plt.subplots(figsize=(4, 3), dpi=100)
title = ax.set_title("short")
label = ax.set_xlabel("x")
fig.canvas.draw()
renderer = fig.canvas.get_renderer()
first = title.get_window_extent(renderer)
title.set_text("a much longer title than before")
second = title.get_window_extent(renderer)
fig.canvas.draw()
third = title.get_window_extent(fig.canvas.get_renderer())
print([round(v, 3) for v in first.bounds])
print([round(v, 3) for v in second.bounds])
print([round(v, 3) for v in third.bounds])
print(fig.canvas.get_renderer() is renderer)
fig.set_dpi(200)
fig.canvas.draw()
print(fig.canvas.get_renderer() is renderer, [round(v, 3) for v in title.get_window_extent().bounds])
print([round(v, 3) for v in label.get_window_extent().bounds])
fig.savefig("kept_renderer.png")
fig.set_size_inches(5, 2)
fig.canvas.draw()
r3 = fig.canvas.get_renderer()
print(r3.width, r3.height, [round(v, 3) for v in ax.bbox.bounds])
print([round(v, 3) for v in ax.get_tightbbox(r3).bounds])
fig.savefig("kept_renderer_resized.png")
