# BboxTransform, BboxTransformFrom/To, TransformedBbox and Bbox arithmetic, checked with exact values.
import numpy as np
from matplotlib.transforms import (Bbox, BboxTransform, BboxTransformFrom, BboxTransformTo, TransformedBbox, Affine2D,
                                   LockableBbox)

src = Bbox.from_extents(0, 0, 4, 2)
dst = Bbox.from_bounds(10, 10, 100, 50)
t = BboxTransform(src, dst)
print(np.round(t.transform([[0, 0], [4, 2], [1, 1]]), 6).tolist(), t.is_affine)
print(np.round(BboxTransformFrom(src).transform([[2, 1]]), 6).tolist(), np.round(BboxTransformTo(dst).transform([[0.5, 0.5]]), 6).tolist())
tb = TransformedBbox(src, Affine2D().rotate_deg(90))
print([round(v, 6) for v in tb.bounds], [round(v, 6) for v in tb.extents])
src.update_from_data_xy(np.array([[-1, -1], [5, 3]]), ignore=False)
print(src.bounds, [round(v, 6) for v in tb.bounds], [round(v, 6) for v in t.transform([[0, 0]])[0]])
u = Bbox.union([Bbox.from_extents(0, 0, 1, 1), Bbox.from_extents(2, -1, 3, 0.5)])
i = Bbox.intersection(Bbox.from_extents(0, 0, 2, 2), Bbox.from_extents(1, 1, 3, 3))
none = Bbox.intersection(Bbox.from_extents(0, 0, 1, 1), Bbox.from_extents(2, 2, 3, 3))
print(u.extents.tolist(), i.extents.tolist(), none)
b = Bbox.from_bounds(1, 2, 3, 4)
print(b.padded(0.5).bounds, b.shrunk(0.5, 0.25).bounds, b.expanded(2, 1).bounds, b.translated(1, 1).bounds)
print(b.anchored("C", Bbox.from_bounds(0, 0, 10, 10)).bounds, b.shrunk_to_aspect(1.0).bounds)
print(b.contains(2, 3), b.fully_contains(1, 2), b.overlaps(Bbox.from_bounds(3.5, 5.5, 1, 1)), b.count_contains([[1.5, 2.5], [9, 9]]))
lock = LockableBbox(b, x0=0)
print(lock.bounds, lock.locked_x0, lock.locked_y1)
print(Bbox.null().bounds, Bbox.unit().bounds, Bbox([[np.inf, np.inf], [-np.inf, -np.inf]]).bounds)
print(b.splitx(0.5)[0].bounds, b.splity(0.25, 0.75)[1].bounds)
print(repr(b), str(Bbox.from_extents(0, 0, 1, 1)))
frozen = tb.frozen()
src.set_points(np.array([[0.0, 0.0], [1.0, 1.0]]))
print([round(v, 6) for v in frozen.bounds], [round(v, 6) for v in tb.bounds])
print(Bbox.from_extents(3, 3, 1, 1).bounds, Bbox.from_extents(3, 3, 1, 1).width)
