/// The report.
pub(super) fn render(report: &Report) -> String {
    let mut out = String::new();
    header(&mut out, report);
    summary::write(&mut out, report);
    methodology::write(&mut out, report);
    startup(&mut out, report);
    for tier in Tier::ALL {
        let rows: Vec<&Measurement> = report
            .measurements
            .iter()
            .filter(|m| m.workload.tier == tier)
            .collect();
        if !rows.is_empty() {
            tier_tables(&mut out, tier, &rows);
        }
    }
    guard(&mut out, report);
    unsupported(&mut out, report);
    methodology::reproduce(&mut out);
    out
}

/// One line on how a workload went, for the progress output.
pub(super) fn progress_line(m: &Measurement) -> String {
    let warm = |name: &str, column: &Column<Samples>| {
        format!("{name} {}", cell(column, |s| ms(s.median())))
    };
    let cold = |name: &str, column: &Column<ColdResult>| {
        format!("{name} {}", cell(column, |c| ms(c.seconds.median())))
    };
    format!(
        "warm ms: {}, {}, {RUST} {} | cold ms: {}, {}, {RUST} {} | guard: {PYTHON} {}, {RUST} {}",
        warm("matplotlib", &m.warm.matplotlib),
        warm(PYTHON, &m.warm.python),
        ms(m.warm.rust.median()),
        cold("matplotlib", &m.cold.matplotlib),
        cold(PYTHON, &m.cold.python),
        ms(m.cold.rust.seconds.median()),
        cell(&m.guard.python, Verdict::to_string),
        m.guard
            .rust
            .as_ref()
            .map_or("-".to_owned(), Verdict::to_string),
    )
}

/// The name of the Python column of pltrs in the report.
pub(super) const PYTHON: &str = "pltrs (Python)";

/// The name of the Rust column of pltrs in the report.
pub(super) const RUST: &str = "pltrs (Rust)";

/// The title, what the columns are and when the numbers were measured.
fn header(out: &mut String, report: &Report) {
    let _ = writeln!(
        out,
        "# Benchmarks of matplotlib, {PYTHON} and {RUST}\n\n\
         <!-- Generated by `cargo xtask bench --report` \
         (xtask/src/bench/report); do not edit by hand. -->\n\n\
         **matplotlib** is matplotlib {} in Python, **{PYTHON}** runs the same scripts with \
         only their import changed, and **{RUST}** draws the same figures from Rust; a \
         speed-up such as \"4.2× faster\" means matplotlib took 4.2 times as long.\n\n\
         These numbers were measured on {} at commit `{}`, on the machine described under \
         [Methodology](#methodology).\n",
        report.versions.reference("matplotlib"),
        report.versions.reference("date"),
        report.machine.revision,
    );
}

/// The start-up and import table.
fn startup(out: &mut String, report: &Report) {
    let s = &report.startup;
    let threads = report.machine.threads;
    out.push_str(
        "## Start-up and imports\n\n\
         These fresh processes only start, import and exit. Every cold run costs at least \
         as much.\n\n\
         | process | median ms (IQR) | peak memory MiB |\n|---|---:|---:|\n",
    );
    let rows = [
        ("`python -c pass`".to_owned(), &s.interpreter),
        ("`python -c \"import numpy\"`".to_owned(), &s.numpy),
        (
            format!("`python -c \"import numpy\"`, OpenBLAS's default {threads} threads"),
            &s.numpy_threaded,
        ),
        (
            "`python -c \"import matplotlib.pyplot\"`".to_owned(),
            &s.matplotlib,
        ),
        ("`python -c \"import pltrs.pyplot\"`".to_owned(), &s.python),
        (
            format!("the benchmark executable of {RUST}, starting and exiting"),
            &s.rust,
        ),
    ];
    for (name, result) in rows {
        let _ = writeln!(
            out,
            "| {name} | {} | {} |",
            timing(&result.seconds),
            mib(result.peak_kib)
        );
    }
    let numpy = s.numpy.seconds.median();
    let _ = writeln!(
        out,
        "\nBoth pyplot modules import numpy. Beyond numpy, importing `matplotlib.pyplot` \
         costs {} ms and importing `pltrs.pyplot` {} ms.\n",
        ms(s.matplotlib.seconds.median() - numpy),
        ms(s.python.seconds.median() - numpy),
    );
}

/// The warm, cold and memory tables of one tier.
fn tier_tables(out: &mut String, tier: Tier, rows: &[&Measurement]) {
    let _ = writeln!(out, "## {}\n", tier.title());
    let header = format!(
        "| workload | matplotlib ms | {PYTHON} ms | speed-up | {RUST} ms | speed-up |\n\
         |---|---:|---:|---:|---:|---:|\n"
    );
    let _ = write!(
        out,
        "### Warm, in-process\n\nEach time is the median of the runs after the warm-up, \
         with the interquartile range in parentheses. Each speed-up compares the time \
         before it with matplotlib's.\n\n{header}"
    );
    for m in rows {
        times_row(out, m, &m.warm, Samples::median, timing);
    }
    let _ = write!(
        out,
        "\n### Cold, end to end\n\nEach run is a fresh process that starts, imports, makes \
         the data, builds the figure and writes the file. Each speed-up compares the time \
         before it with matplotlib's.\n\n{header}"
    );
    for m in rows {
        times_row(
            out,
            m,
            &m.cold,
            |c: &ColdResult| c.seconds.median(),
            |c: &ColdResult| timing(&c.seconds),
        );
    }
    let _ = write!(
        out,
        "\n### Peak memory, cold\n\nEach cell is the peak resident memory of the cold \
         process, the median over its runs.\n\n\
         | workload | matplotlib MiB | {PYTHON} MiB | {RUST} MiB |\n|---|---:|---:|---:|\n",
    );
    for m in rows {
        let peak = |c: &ColdResult| mib(c.peak_kib);
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            m.workload.name,
            cell(&m.cold.matplotlib, peak),
            cell(&m.cold.python, peak),
            peak(&m.cold.rust),
        );
    }
    per_call(out, rows);
    out.push_str(&footnotes(rows));
}

/// What the Python layer of pltrs (Python) adds to each call, for the
/// workloads of many calls among `rows`.
fn per_call(out: &mut String, rows: &[&Measurement]) {
    let counted: Vec<(&Measurement, u32)> = rows
        .iter()
        .filter_map(|m| Some((*m, m.workload.calls?)))
        .collect();
    if counted.is_empty() {
        return;
    }
    let _ = write!(
        out,
        "\n### What a call costs in {PYTHON}\n\n{PYTHON} and {RUST} run the same Rust code \
         for these figures. On every call {PYTHON} also handles matplotlib's signature and \
         keywords, converts the arguments, crosses into the extension and makes the Python \
         object of the artist it returns. The table divides the difference of their warm \
         medians by the number of calls.\n\n\
         | workload | calls | extra per call, µs |\n|---|---:|---:|\n",
    );
    for (m, calls) in counted {
        let extra = cell(&m.warm.python, |python| {
            format!(
                "{:.1}",
                (python.median() - m.warm.rust.median()) * 1e6 / f64::from(calls)
            )
        });
        let _ = writeln!(out, "| `{}` | {calls} | {extra} |", m.workload.name);
    }
}

/// A row of times: matplotlib's, then those of pltrs (Python) and pltrs
/// (Rust), each followed by its speed-up over matplotlib's median.
fn times_row<T>(
    out: &mut String,
    m: &Measurement,
    columns: &Columns<T>,
    median: impl Fn(&T) -> f64,
    shown: impl Fn(&T) -> String,
) {
    let reference = columns.matplotlib.measured().map(&median);
    let speedup_of = |value: Option<f64>, diverges: bool| match (value, reference) {
        (Some(value), Some(reference)) => {
            let mark = if diverges { " †" } else { "" };
            format!("{}{mark}", speedup(value / reference))
        }
        _ => "n/a".to_owned(),
    };
    let python_diverges = m.guard.python.measured().is_some_and(Verdict::diverges);
    let rust_diverges = m.guard.rust.as_ref().is_some_and(Verdict::diverges);
    let _ = writeln!(
        out,
        "| `{}` | {} | {} | {} | {} | {} |",
        m.workload.name,
        cell(&columns.matplotlib, &shown),
        cell(&columns.python, &shown),
        speedup_of(columns.python.measured().map(&median), python_diverges),
        shown(&columns.rust),
        speedup_of(Some(median(&columns.rust)), rust_diverges),
    );
}

/// The notes under a tier's tables: the marks used and the workloads not
/// comparable.
fn footnotes(rows: &[&Measurement]) -> String {
    let mut notes = String::new();
    if rows.iter().any(|m| {
        m.guard.python.measured().is_some_and(Verdict::diverges)
            || m.guard.rust.as_ref().is_some_and(Verdict::diverges)
    }) {
        notes.push_str(
            "\n† The figure differs from matplotlib's beyond the guard's tolerance, as \
             [Correctness guard](#correctness-guard) shows.\n",
        );
    }
    for m in rows {
        if let Column::NotComparable(why) = &m.warm.matplotlib {
            let _ = writeln!(
                notes,
                "\n`{}` is not comparable, because {why}.",
                m.workload.name
            );
        }
    }
    notes.push('\n');
    notes
}

/// The guard's verdicts for every workload.
fn guard(out: &mut String, report: &Report) {
    let _ = write!(
        out,
        "## Correctness guard\n\nBefore the harness times a workload, each implementation \
         saves its figure as PNG. The RMS difference of the channel values (0 to 255) from \
         matplotlib's PNG must be at most {TOLERANCE}. The PNGs, and the difference images \
         of failures, are in `target/bench/guard/`.\n\n\
         | workload | {PYTHON} vs matplotlib | {RUST} vs matplotlib |\n|---|---|---|\n"
    );
    for m in &report.measurements {
        let rust = m
            .guard
            .rust
            .as_ref()
            .map_or_else(|| "not comparable".to_owned(), verdict);
        let _ = writeln!(
            out,
            "| `{}` | {} | {rust} |",
            m.workload.name,
            cell(&m.guard.python, verdict)
        );
    }
    out.push('\n');
}

/// A verdict in a table, failures in bold.
fn verdict(verdict: &Verdict) -> String {
    if verdict.diverges() {
        format!("**differs** ({verdict})")
    } else {
        verdict.to_string()
    }
}

/// The workloads pltrs (Python) cannot run yet, with the exception each
/// raised.
fn unsupported(out: &mut String, report: &Report) {
    let missing: Vec<(&str, &str)> = report
        .measurements
        .iter()
        .filter_map(|m| match &m.warm.python {
            Column::NotSupported(why) => Some((m.workload.name, why.as_str())),
            Column::Measured(_) | Column::NotComparable(_) => None,
        })
        .collect();
    if missing.is_empty() {
        return;
    }
    let _ = write!(
        out,
        "## Not supported yet by {PYTHON}\n\nEach row gives the exception the script raised \
         under {PYTHON}. As it grows, rerunning the report moves these workloads into the \
         tables.\n\n\
         | workload | exception |\n|---|---|\n",
    );
    for (name, why) in missing {
        let why = why.replace('|', "\\|");
        let shortened: String = why.chars().take(160).collect();
        let ellipsis = if why.chars().count() > shortened.chars().count() {
            "…"
        } else {
            ""
        };
        let _ = writeln!(out, "| `{name}` | {shortened}{ellipsis} |");
    }
    out.push('\n');
}

/// What a Python column shows: `shown` of its value, or why it has none.
fn cell<T>(column: &Column<T>, shown: impl Fn(&T) -> String) -> String {
    match column {
        Column::Measured(value) => shown(value),
        Column::NotSupported(_) => "not supported yet".to_owned(),
        Column::NotComparable(_) => "not comparable".to_owned(),
    }
}

/// A duration given in seconds, in milliseconds to three significant
/// digits or so.
fn ms(seconds: f64) -> String {
    let ms = seconds * 1e3;
    // The bounds are where rounding reaches 10.00 and 100.0.
    if ms.abs() < 9.995 {
        format!("{ms:.2}")
    } else if ms.abs() < 99.95 {
        format!("{ms:.1}")
    } else {
        format!("{ms:.0}")
    }
}

/// The median and interquartile range of `samples`, in milliseconds.
fn timing(samples: &Samples) -> String {
    let (q1, q3) = samples.quartiles();
    format!("{} ({}–{})", ms(samples.median()), ms(q1), ms(q3))
}

/// A size given in KiB, in MiB.
fn mib(kib: u64) -> String {
    format!("{:.0}", kib as f64 / 1024.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_read_well() {
        assert_eq!(ms(0.001_234), "1.23");
        assert_eq!(ms(0.012_34), "12.3");
        assert_eq!(ms(1.234), "1234");
        assert_eq!(ms(0.009_999), "10.0");
        assert_eq!(ms(0.099_99), "100");
        assert_eq!(mib(2048), "2");
    }

    #[test]
    fn cells_say_why_they_are_empty() {
        let missing: Column<f64> = Column::NotSupported("AttributeError".to_owned());
        assert_eq!(cell(&missing, f64::to_string), "not supported yet");
        assert_eq!(cell(&Column::Measured(1.5), f64::to_string), "1.5");
    }
}
