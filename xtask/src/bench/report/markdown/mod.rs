/// Where the report links to the scripts and the Rust workloads, from
/// the directory it is written to (`benchmarks/` itself, or another
/// machine's report such as `benchmarks/macos/`).
#[derive(Debug, PartialEq)]
pub(super) struct Links {
    /// The Python scripts, `benchmarks/python`.
    python: String,
    /// The Rust workloads, `xtask/src/bench/workloads`.
    workloads: String,
}

impl Links {
    /// The links from a report in `dir` (relative to the working
    /// directory, as `--to` names it, or absolute): relative within the
    /// workspace, absolute outside it.
    pub(super) fn for_dir(dir: &Path) -> Self {
        let dir = std::path::absolute(dir).unwrap_or_else(|_| dir.to_path_buf());
        Self::within(&crate::python::root(), &dir)
    }

    /// The links from a report in `dir` of the workspace `root`.
    fn within(root: &Path, dir: &Path) -> Self {
        let link = |target: &str| match dir.strip_prefix(root) {
            Ok(inside) => relative(inside, Path::new(target)),
            Err(_) => forward_slashes(&root.join(target)),
        };
        Self {
            python: link("benchmarks/python"),
            workloads: link("xtask/src/bench/workloads"),
        }
    }
}

/// `path` with forward slashes, as links take them (Windows' separators
/// turned).
fn forward_slashes(path: &Path) -> String {
    let text = path.display().to_string();
    if std::path::MAIN_SEPARATOR == '\\' {
        text.replace('\\', "/")
    } else {
        text
    }
}

/// The path from the directory `from` to `to`, both relative to the same
/// root, with forward slashes.
fn relative(from: &Path, to: &Path) -> String {
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let ups = std::iter::repeat_n("..".to_owned(), from.len() - common);
    let downs = to[common..]
        .iter()
        .map(|part| part.as_os_str().to_string_lossy().into_owned());
    ups.chain(downs).collect::<Vec<_>>().join("/")
}

/// The report.
pub(super) fn render(results: &Results, charts: &Charts, links: &Links) -> String {
    let mut out = String::new();
    header(&mut out, results);
    summary::write(&mut out, results, charts);
    fairness::write(&mut out, results, links);
    tables::write(&mut out, results);
    fairness::reproduce(&mut out);
    out
}

/// One line on how a workload went, for the progress output.
pub(super) fn progress_line(w: &WorkloadResult) -> String {
    let mut line = String::new();
    for mode in Mode::ALL {
        let _ = write!(line, "{} ms:", mode.name());
        for implementation in Implementation::ALL {
            let shown = match mode {
                Mode::Warm => cell(w.warm.get(implementation), |m| ms(m.seconds.median())),
                Mode::Cold => cell(w.cold.get(implementation), |c: &ColdResult| {
                    ms(c.seconds.median())
                }),
            };
            let _ = write!(line, " {} {shown},", implementation.key());
        }
        line.push(' ');
    }
    for contender in Implementation::CONTENDERS {
        let verdict = w.guard.of(contender).map_or_else(String::new, |guard| {
            cell(guard, |g| {
                let failures = g.failures();
                if failures.is_empty() {
                    "same".to_owned()
                } else {
                    failures.join("; ")
                }
            })
        });
        let _ = write!(line, "guard {}: {verdict}. ", contender.key());
    }
    line.trim_end().to_owned()
}

/// The title, what the columns are and when the numbers were measured.
fn header(out: &mut String, results: &Results) {
    let _ = writeln!(
        out,
        "# Benchmarks of matplotlib, pltrs (Python) and pltrs (Rust)\n\n\
         <!-- Generated by `cargo xtask bench --report` (xtask/src/bench/report) from \
         results.json; do not edit by hand. -->\n\n\
         This report times matplotlib {mpl} against both faces of pltrs on {n} workloads. \
         pltrs (Python) runs the same Python scripts as matplotlib with only their imports \
         changed. pltrs (Rust) draws the same figures from Rust. A speed-up such as \"4.2× \
         faster\" means that matplotlib took 4.2 times as long.\n\n\
         The numbers were measured on {date} at commit `{revision}`, on {machine} \
         described under [Machine and versions](#machine-and-versions). Every time of every \
         run is in [`results.json`](results.json). pltrs (Rust) drew the charts from that \
         file (`cargo xtask bench --rewrite-report` draws them again).\n",
        mpl = results.versions.reference("matplotlib"),
        n = results.workloads.len(),
        date = results.versions.reference("date"),
        revision = results.machine.revision,
        machine = results
            .machine
            .model
            .as_ref()
            .map_or_else(|| "the machine".to_owned(), |model| format!("a {model},")),
    );
}

/// What a column shows: `shown` of its value, or why it has none.
fn cell<T>(column: &Column<T>, shown: impl Fn(&T) -> String) -> String {
    match column {
        Column::Measured(value) => shown(value),
        Column::NotSupported(_) => "not supported yet".to_owned(),
        Column::NotComparable(_) => "not comparable".to_owned(),
    }
}

/// A duration given in seconds, in milliseconds to three significant
/// digits or so.
fn ms(seconds: f64) -> String {
    let ms = seconds * 1e3;
    // The bounds are where rounding reaches 10.00 and 100.0.
    if ms.abs() < 9.995 {
        format!("{ms:.2}")
    } else if ms.abs() < 99.95 {
        format!("{ms:.1}")
    } else {
        format!("{ms:.0}")
    }
}

/// The median and interquartile range of `samples`, in milliseconds.
fn timing(samples: &Samples) -> String {
    let (q1, q3) = samples.quartiles();
    format!("{} [{}, {}]", ms(samples.median()), ms(q1), ms(q3))
}

/// A size given in KiB, in MiB.
fn mib(kib: u64) -> String {
    format!("{:.0}", kib as f64 / 1024.0)
}

/// A speed-up with its 95% interval, in the direction it is worded:
/// `4.2× faster [4.0, 4.4]`, `1.27× slower [1.20, 1.31]`.
fn speedup_interval(ratio: &Ratio) -> String {
    let (low, high) = if ratio.value < 1.0 {
        (factor_of(ratio.high), factor_of(ratio.low))
    } else {
        (factor_of(1.0 / ratio.low), factor_of(1.0 / ratio.high))
    };
    format!("{} [{low}, {high}]", speedup(ratio.value))
}

/// A typical ratio as a speed-up, `n/a` without one.
fn typical(ratio: Option<f64>) -> String {
    ratio.map_or_else(|| "n/a".to_owned(), speedup)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bench::results::tests::sample;

    #[test]
    fn links_lead_from_the_report_to_the_scripts() {
        let root = Path::new("/work");
        let here = Links::within(root, &root.join("benchmarks"));
        assert_eq!(here.python, "python");
        assert_eq!(here.workloads, "../xtask/src/bench/workloads");
        let macos = Links::within(root, &root.join("benchmarks/macos"));
        assert_eq!(macos.python, "../python");
        assert_eq!(macos.workloads, "../../xtask/src/bench/workloads");
        let outside = Links::within(root, Path::new("/elsewhere"));
        assert_eq!(outside.python, "/work/benchmarks/python");
    }

    #[test]
    fn numbers_read_well() {
        assert_eq!(ms(0.001_234), "1.23");
        assert_eq!(ms(0.012_34), "12.3");
        assert_eq!(ms(1.234), "1234");
        assert_eq!(ms(0.009_999), "10.0");
        assert_eq!(ms(0.099_99), "100");
        assert_eq!(mib(2048), "2");
        let faster = Ratio {
            value: 0.25,
            low: 0.2,
            high: 0.3,
        };
        assert_eq!(speedup_interval(&faster), "4.0× faster [3.3, 5.0]");
        let slower = Ratio {
            value: 1.27,
            low: 1.2,
            high: 1.31,
        };
        assert_eq!(speedup_interval(&slower), "1.27× slower [1.20, 1.31]");
    }

    #[test]
    fn cells_say_why_they_are_empty() {
        let missing: Column<f64> = Column::NotSupported("AttributeError".to_owned());
        assert_eq!(cell(&missing, f64::to_string), "not supported yet");
        assert_eq!(cell(&Column::Measured(1.5), f64::to_string), "1.5");
    }

    #[test]
    fn the_report_covers_every_section() {
        let results = sample();
        let charts = Charts::default();
        let links = Links::within(Path::new("/work"), Path::new("/work/benchmarks"));
        let report = render(&results, &charts, &links);
        for heading in [
            "## Summary",
            "### pltrs (Python) as a drop-in replacement for matplotlib",
            "### pltrs (Rust) against matplotlib",
            "## How the comparison is kept fair",
            "## What is not compared",
            "## Machine and versions",
            "## Correctness guard",
            "## Reproducing",
        ] {
            assert!(report.contains(heading), "{heading}");
        }
        assert!(report.contains("`small/line_svg`"));
        assert!(report.contains("[`benchmarks/python`](python)"));
        assert!(!report.contains('—'), "no em dashes in the report");
        assert!(progress_line(&results.workloads[0]).contains("guard pltrs-rust: same."));
    }
}
