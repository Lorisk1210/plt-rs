//! The report as Markdown: the summary of each claim, the rules that keep
//! the comparison fair, the machine, a table per tier and measurement,
//! the guard's verdicts, and how to reproduce it all.

mod fairness;
mod summary;
mod tables;

use std::fmt::Write as _;
use std::path::Path;

use super::super::cold::ColdResult;
use super::super::implementation::Implementation;
use super::super::results::{Column, Results, WorkloadResult};
use super::super::stats::{Ratio, Samples, factor_of, speedup};
